//! Turns the data relocations of a linked module into its rebase table.
//!
//! The module is linked once with an empty table and its relocations kept.
//! Every data word that holds an absolute address becomes one entry here:
//! the word's own link address. The module is then linked again with the
//! table in it, and its start-up adds the code or data load delta to each
//! word, by which range the stored value is in.
//!
//! Anything the start-up could not put right stops the build:
//!
//! * a site outside the data range. Code is run in place and is never
//!   written, so a word there cannot be patched;
//! * a stored value in neither link range, which has no delta to add;
//! * a relocation that is not one whole word;
//! * any dynamic relocation, which this mechanism does not use and nothing
//!   would apply.

const std = @import("std");
const elf = std.elf;
const arm = @import("arm.zig");
const check = @import("check.zig");
const elf32 = @import("elf32.zig");
const layout = @import("layout.zig");
const records = @import("records.zig");

pub const Error = elf32.Error || error{
    /// The image does not name its link ranges, so it is not a module.
    NotAModule,
    SiteInCode,
    ValueOutsideModule,
    NotAWholeWord,
    DynamicRelocation,
    /// More sites than a table can be built for.
    TooManySites,
};

/// The section the table goes in. The module linker script gathers it into
/// `.rodata`, inside the size the module manager maps as the module's code.
pub const section = ".rodata.txm_rebase";

pub const max_sites = 4096;

/// What stopped the table from being built: the site and its stored value.
pub const Problem = struct {
    site: check.Finding,
    stored: u32,
};

/// The link addresses of every data word of `image` that needs rebasing,
/// in ascending order, into `out`. On a site-specific error `problem` says
/// which site.
pub fn sites(image: []const u8, out: []u32, problem: *?Problem) Error![]u32 {
    const file = try elf32.File.init(image);
    const ranges = try layout.Layout.read(file) orelse return error.NotAModule;
    try refuseDynamic(file);

    var walk = try check.Iterator.init(image);
    var count: usize = 0;
    while (try walk.next()) |site| : (count += 1) {
        const stored = try file.wordAt(site.address) orelse 0;
        problem.* = .{ .site = site, .stored = stored };
        if (!arm.isWholeWord(site.kind)) return error.NotAWholeWord;
        if (ranges.region(site.address) != .data) return error.SiteInCode;
        if (ranges.region(stored) == .outside) return error.ValueOutsideModule;
        if (count == out.len) return error.TooManySites;
        out[count] = site.address;
    }
    problem.* = null;
    std.mem.sort(u32, out[0..count], {}, std.sort.asc(u32));
    return out[0..count];
}

/// A dynamic relocation section with anything in it is an error. Those are
/// the loaded ones; the sections `--emit-relocs` keeps are not loaded.
fn refuseDynamic(file: elf32.File) Error!void {
    for (0..file.section_count) |index| {
        const found = try file.section(@intCast(index));
        if (found.kind != elf.SHT_REL and found.kind != elf.SHT_RELA) continue;
        const named = std.mem.endsWith(u8, found.name, ".dyn") or
            std.mem.endsWith(u8, found.name, ".plt");
        if (found.flags & elf.SHF_ALLOC == 0 and !named) continue;
        if (found.bytes.len != 0) return error.DynamicRelocation;
    }
}

/// Write the table for `addresses` as assembly, leaving out the entry at
/// index `leave_out` if there is one. That switch exists for the build's
/// own negative probe: a table that misses a site must fail the check.
pub fn write(writer: anytype, addresses: []const u32, leave_out: ?usize) !void {
    try writer.writeAll(
        \\/* Generated by tools/check_txm_module_relocs. Do not edit, and do not
        \\   check in: this is a build output. One word for each data word the
        \\   module's start-up rebases. */
        \\    .syntax unified
        \\
    );
    try writer.print("    .section {s},\"a\",%progbits\n    .balign 4\n", .{section});
    try writer.print("    .global {s}\n", .{records.Names.start});
    try writer.print("    .global {s}\n", .{records.Names.end});
    try writer.print("{s}:\n", .{records.Names.start});
    for (addresses, 0..) |address, index| {
        if (leave_out == index) continue;
        try writer.print("    .word 0x{x:0>8}\n", .{address});
    }
    try writer.print("{s}:\n", .{records.Names.end});
}
