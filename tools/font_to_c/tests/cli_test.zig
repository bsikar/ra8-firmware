test "an existing output file is overwritten, not appended to" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();
    try tmp.dir.writeFile(.{ .sub_path = "font.ttf", .data = &.{0x01} });
    try tmp.dir.writeFile(.{ .sub_path = "out.c", .data = "stale content that must not survive\n" });

    const status = try run(
        tmp.dir,
        &streams,
        &.{ "font_to_c", "font.ttf", "out.c", "g_font", "font.h" },
    );

    try std.testing.expectEqual(cli.exit_ok, status);
    const written = try tmp.dir.readFileAlloc(std.testing.allocator, "out.c", 4096);
    defer std.testing.allocator.free(written);
    try std.testing.expect(std.mem.indexOf(u8, written, "stale") == null);
}

test "the emitted symbol and header come from argv" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();
    try tmp.dir.writeFile(.{ .sub_path = "literata_latin1.ttf", .data = &.{ 0x10, 0x20 } });

    const status = try run(tmp.dir, &streams, &.{
        "font_to_c",
        "literata_latin1.ttf",
        "baked.c",
        "g_ra8_font_literata_latin1",
        "literata_latin1.h",
    });

    try std.testing.expectEqual(cli.exit_ok, status);
    const written = try tmp.dir.readFileAlloc(std.testing.allocator, "baked.c", 4096);
    defer std.testing.allocator.free(written);
    try std.testing.expect(
        std.mem.indexOf(u8, written, "#include \"literata_latin1.h\"") != null,
    );
    try std.testing.expect(
        std.mem.indexOf(u8, written, "const unsigned int g_ra8_font_literata_latin1_len = 2U;") != null,
    );
}

test "a nested input path is named by its basename in the provenance comment" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();
    try tmp.dir.makeDir("fonts");
    try tmp.dir.writeFile(.{ .sub_path = "fonts/nested.ttf", .data = &.{0x05} });

    const status = try run(
        tmp.dir,
        &streams,
        &.{ "font_to_c", "fonts/nested.ttf", "out.c", "g_font", "font.h" },
    );

    try std.testing.expectEqual(cli.exit_ok, status);
    const written = try tmp.dir.readFileAlloc(std.testing.allocator, "out.c", 4096);
    defer std.testing.allocator.free(written);
    try std.testing.expect(
        std.mem.indexOf(u8, written, "/* Source: nested.ttf (1 bytes). */") != null,
    );
}
