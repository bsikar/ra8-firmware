test "exit 1 when the font cannot be read" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();

    const status = try run(
        tmp.dir,
        &streams,
        &.{ "font_to_c", "missing.ttf", "out.c", "g_font", "font.h" },
    );

    try std.testing.expectEqual(cli.exit_error, status);
    try std.testing.expect(std.mem.indexOf(u8, streams.err.items, "missing.ttf") != null);
    try std.testing.expectEqualStrings("", streams.out.items);
}

test "exit 1 on an empty font rather than a zero-length array" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();
    try tmp.dir.writeFile(.{ .sub_path = "empty.ttf", .data = "" });

    const status = try run(
        tmp.dir,
        &streams,
        &.{ "font_to_c", "empty.ttf", "out.c", "g_font", "font.h" },
    );

    try std.testing.expectEqual(cli.exit_error, status);
    try std.testing.expectEqualStrings("font_to_c: empty input empty.ttf\n", streams.err.items);
    try std.testing.expectError(error.FileNotFound, tmp.dir.access("out.c", .{}));
}

test "exit 0 writes the translation unit" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var streams = Streams.init(std.testing.allocator);
    defer streams.deinit();
    try tmp.dir.writeFile(.{ .sub_path = "font.ttf", .data = &.{ 0x00, 0x01, 0xFE } });

    const status = try run(
        tmp.dir,
        &streams,
        &.{ "font_to_c", "font.ttf", "out.c", "g_font", "font.h" },
    );

    try std.testing.expectEqual(cli.exit_ok, status);
    try std.testing.expectEqualStrings("", streams.err.items);

    const written = try tmp.dir.readFileAlloc(std.testing.allocator, "out.c", 4096);
    defer std.testing.allocator.free(written);
    try std.testing.expectEqualStrings(
        \\/* GENERATED by tools/font_to_c -- do not edit. */
        \\/* Source: font.ttf (3 bytes). */
        \\#include "font.h"
        \\
        \\const unsigned char g_font[] = {
        \\  0x00, 0x01, 0xFE,
        \\};
        \\const unsigned int g_font_len = 3U;
        \\
    ,
        written,
    );
}

