//! Rendering algebra of `font_to_c` (#858). The generated translation unit is
//! compiled straight into three firmware images, so these cases pin the shape
//! the per-font header is declared against: the two symbols, the 16-byte row,
//! uppercase zero-padded literals, and the `U` suffix on the length.

const std = @import("std");
const implementation = @import("implementation");

fn render(data: []const u8) ![]u8 {
    return implementation.render(
        std.testing.allocator,
        "literata_latin1.ttf",
        data,
        "g_ra8_font_literata_latin1",
        "literata_latin1.h",
    );
}

test "basename keeps the trailing component of a POSIX path" {
    try std.testing.expectEqualStrings(
        "literata_latin1.ttf",
        implementation.basename("libs/ra8_fonts/literata_latin1.ttf"),
    );
}

test "basename keeps the trailing component of a Windows path" {
    try std.testing.expectEqualStrings(
        "literata_latin1.ttf",
        implementation.basename("libs\\ra8_fonts\\literata_latin1.ttf"),
    );
}

test "basename passes a bare file name through" {
    try std.testing.expectEqualStrings("font.ttf", implementation.basename("font.ttf"));
}

test "the provenance comment names the tool, not the deleted script" {
    const text = try render(&.{0x01});
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.startsWith(
        u8,
        text,
        "/* GENERATED by tools/font_to_c -- do not edit. */\n",
    ));
}

test "the source comment carries the font name and its byte count" {
    const text = try render(&.{ 0x01, 0x02, 0x03 });
    defer std.testing.allocator.free(text);

    try std.testing.expect(
        std.mem.indexOf(u8, text, "/* Source: literata_latin1.ttf (3 bytes). */\n") != null,
    );
}

test "the unit includes the per-font header so definitions are checked" {
    const text = try render(&.{0xFF});
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "#include \"literata_latin1.h\"\n\n") != null);
}

test "the array is defined against the requested symbol" {
    const text = try render(&.{0xFF});
    defer std.testing.allocator.free(text);

    try std.testing.expect(
        std.mem.indexOf(u8, text, "const unsigned char g_ra8_font_literata_latin1[] = {\n") != null,
    );
}

test "the length constant carries the U suffix" {
    const text = try render(&.{ 0x00, 0x01, 0x02, 0x03 });
    defer std.testing.allocator.free(text);

    try std.testing.expect(
        std.mem.indexOf(u8, text, "const unsigned int g_ra8_font_literata_latin1_len = 4U;\n") != null,
    );
}

test "byte literals are uppercase and zero padded" {
    const text = try render(&.{ 0x00, 0x0A, 0xAB });
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "  0x00, 0x0A, 0xAB,\n") != null);
}

test "a full row carries exactly sixteen literals" {
    var data: [implementation.bytes_per_row]u8 = undefined;
    for (&data, 0..) |*byte, index| byte.* = @intCast(index);

    const text = try render(&data);
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(
        u8,
        text,
        "  0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,\n",
    ) != null);
}

test "seventeen bytes wrap onto a second, shorter row" {
    var data: [implementation.bytes_per_row + 1]u8 = undefined;
    for (&data, 0..) |*byte, index| byte.* = @intCast(index);

    const text = try render(&data);
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "\n  0x10,\n};\n") != null);
}

test "a single byte renders as one row" {
    const text = try render(&.{0x7F});
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "{\n  0x7F,\n};\n") != null);
}

test "the rendered unit ends in a newline" {
    const text = try render(&.{ 0x01, 0x02 });
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.endsWith(u8, text, ";\n"));
    try std.testing.expectEqual(@as(u8, '\n'), text[text.len - 1]);
}

test "the symbol name is used for both the array and the length" {
    const text = try implementation.render(
        std.testing.allocator,
        "other.ttf",
        &.{0x2A},
        "g_other_font",
        "other.h",
    );
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "const unsigned char g_other_font[] = {") != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "const unsigned int g_other_font_len = 1U;") != null);
}

test "appendRow indents two spaces and comma-terminates every literal" {
    var out = std.ArrayList(u8).init(std.testing.allocator);
    defer out.deinit();

    try implementation.appendRow(&out, &.{ 0xDE, 0xAD });

    try std.testing.expectEqualStrings("  0xDE, 0xAD,", out.items);
}
