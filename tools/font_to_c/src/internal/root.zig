//! Pure C-source rendering for the `font_to_c` build tool (#858).
//!
//! No file system and no process state: a byte blob in, the text of a C
//! translation unit out. The emitted unit defines the two symbols the
//! per-font header declares (`<symbol>[]` and `<symbol>_len`) and is written
//! to the build directory rather than committed, which is why the large hex
//! array never reaches the magic-number and formatting gates.
//!
//! The row shape is fixed at 16 bytes, uppercase, zero padded, because the
//! generated file is read by a human exactly once: when a font bake looks
//! wrong.

const std = @import("std");

/// Bytes rendered per row of the generated array.
pub const bytes_per_row = 16;

/// The trailing component of `path`, for the provenance comment.
///
/// Both separators are honoured so a Windows build host names the font the
/// same way a POSIX one does; the generated file is compared across hosts
/// when a bake is in question.
pub fn basename(path: []const u8) []const u8 {
    if (std.mem.lastIndexOfAny(u8, path, "/\\")) |index| return path[index + 1 ..];
    return path;
}

/// Append one row of byte literals to `out`, without its line terminator.
///
/// The row is indented two spaces and every literal carries a trailing comma,
/// including the last one on the line, so rows concatenate in any order.
pub fn appendRow(out: *std.ArrayList(u8), chunk: []const u8) !void {
    try out.appendSlice("  ");
    for (chunk, 0..) |byte, index| {
        if (index != 0) try out.append(' ');
        try out.writer().print("0x{X:0>2},", .{byte});
    }
}

/// Render the C translation unit embedding `data` as `symbol`.
///
/// `source_name` names the font in the provenance comment, `header` is the
/// per-font header the unit includes so the definitions are checked against
/// their declarations. The returned text is owned by the caller and always
/// ends in a newline.
pub fn render(
    allocator: std.mem.Allocator,
    source_name: []const u8,
    data: []const u8,
    symbol: []const u8,
    header: []const u8,
) ![]u8 {
    var text = std.ArrayList(u8).init(allocator);
    errdefer text.deinit();
    const writer = text.writer();

    try writer.print("/* GENERATED by tools/font_to_c -- do not edit. */\n", .{});
    try writer.print("/* Source: {s} ({d} bytes). */\n", .{ source_name, data.len });
    try writer.print("#include \"{s}\"\n\n", .{header});
    try writer.print("const unsigned char {s}[] = {{\n", .{symbol});

    var offset: usize = 0;
    while (offset < data.len) : (offset += bytes_per_row) {
        const end = @min(offset + bytes_per_row, data.len);
        try appendRow(&text, data[offset..end]);
        try text.append('\n');
    }

    try writer.print("}};\n", .{});
    try writer.print("const unsigned int {s}_len = {d}U;\n", .{ symbol, data.len });

    return text.toOwnedSlice();
}
