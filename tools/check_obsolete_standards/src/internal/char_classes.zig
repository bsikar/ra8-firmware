//! Unicode character classes CPython's `re` module applies to a `str`
//! pattern, generated from the interpreter this repository pins and checked
//! in so the Zig gate needs no Python at runtime (#858). Tables copied
//! verbatim from `tools/check_since_version`, which generated them.
//!
//! Two tables, and the obsolete-standards gate needs both:
//!
//!   * `word_intervals` is `\w` for a str pattern, i.e.
//!     `Py_UNICODE_ISALNUM(ch) || ch == '_'`. `FORBIDDEN_PATTERNS` wraps both
//!     spellings in `\b`, and a Python word boundary is decided by that
//!     table, so `DO-178Bx` stays quiet while `DO-178B.` fires, for a
//!     non-ASCII letter exactly as much as for an ASCII one.
//!   * `space_intervals` is `\s` for a str pattern. CPython resolves that to
//!     `Py_UNICODE_ISSPACE`, which is also what `str.isspace` (and therefore
//!     the `line.rstrip()` each finding is reported through) tests, so ONE
//!     table serves both. That equality was verified against the interpreter
//!     when this file was generated, not assumed.

/// One inclusive code-point run.
pub const Interval = struct { low: u21, high: u21 };

/// Binary search a sorted, non-overlapping interval table.
pub fn inTable(table: []const Interval, code_point: u21) bool {
    var low: usize = 0;
    var high: usize = table.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        const entry = table[mid];
        if (code_point < entry.low) {
            high = mid;
        } else if (code_point > entry.high) {
            low = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

