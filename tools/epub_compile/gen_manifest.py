#!/usr/bin/env python3
"""Generate libs/ra_book/inc/ra_book_library.h from compiled .rabook blobs.

Scans a directory of .rabook files, reads each one's title/author/language and
its on-disk and inflated sizes, and emits a C header exposing a static table
(`g_ra_book_library[]`) so firmware can list the bundled library and size the
inflate scratch buffer with a single #include. ASCII-only output (titles are
transliterated) to satisfy the repository encoding policy.

@copyright Copyright (c) 2026 Brighton Sikarskie
SPDX-License-Identifier: MIT
"""

import argparse
import os
import struct
import unicodedata
import zlib


def ascii_only(text):
    norm = unicodedata.normalize("NFKD", text)
    out = norm.encode("ascii", "ignore").decode("ascii")
    return out.replace('"', "'").replace("\\", "")


def read_meta(path):
    with open(path, "rb") as fh:
        container = fh.read()
    if container[:4] != b"RBKZ":
        msg = f"{path}: not a .rabook container"
        raise ValueError(msg)
    inflated_size = struct.unpack("<I", container[4:8])[0]
    flat = zlib.decompress(container[8:])
    h = struct.unpack("<8s23I", flat[:100])
    string_off = h[19]

    def s(off):
        start = string_off + off
        end = flat.index(b"\x00", start)
        return flat[start:end].decode("utf-8", "replace")

    return {
        "title": s(h[4]),
        "author": s(h[5]),
        "language": s(h[6]),
        "file_size": len(container),
        "inflated_size": inflated_size,
        "chapters": h[9],
        "images": h[17],
    }


def main():
    ap = argparse.ArgumentParser(description="Generate the ra_book library manifest header.")
    ap.add_argument("compiled_dir", help="directory of .rabook files")
    ap.add_argument("output", help="path to the generated header")
    args = ap.parse_args()

    files = sorted(f for f in os.listdir(args.compiled_dir) if f.endswith(".rabook"))
    entries = []
    for name in files:
        meta = read_meta(os.path.join(args.compiled_dir, name))
        meta["filename"] = name
        entries.append(meta)

    lines = []
    lines.append("/**")
    lines.append(" * @file ra_book_library.h")
    lines.append(" * @brief Auto-generated index of the compiled e-book library.")
    lines.append(" *")
    lines.append(" * @details")
    lines.append(" * Generated by tools/epub_compile/gen_manifest.py from the .rabook blobs in")
    lines.append(" * content/compiled. DO NOT EDIT BY HAND -- re-run the generator instead. Each")
    lines.append(" * entry names a book and the scratch size its `ra_book_open()` needs.")
    lines.append(" *")
    lines.append(" * @since Version 1.0.0")
    lines.append(" */")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("/**")
    lines.append(" * @struct ra_book_library_entry_t")
    lines.append(" * @brief One bundled book: display metadata plus storage/inflate sizes.")
    lines.append(" * @since Version 1.0.0")
    lines.append(" */")
    lines.append("typedef struct {")
    lines.append("  const char* title;       /**< Book title (transliterated to ASCII).      */")
    lines.append("  const char* author;      /**< Author (transliterated to ASCII).          */")
    lines.append("  const char* filename;    /**< `.rabook` file name on storage.            */")
    lines.append("  uint32_t    file_size;   /**< Compressed size on disk, bytes.            */")
    lines.append("  uint32_t    inflated_size; /**< Scratch bytes ra_book_open() needs.      */")
    lines.append("} ra_book_library_entry_t;")
    lines.append("")
    lines.append("/**")
    lines.append(" * @enum ra_book_library_count_t")
    lines.append(" * @brief Number of books in @ref g_ra_book_library.")
    lines.append(" * @since Version 1.0.0")
    lines.append(" */")
    lines.append("typedef enum : uint16_t {")
    lines.append(f"  k_ra_book_library_count = {len(entries)}U, /**< Bundled book count. */")
    lines.append("} ra_book_library_count_t;")
    lines.append("")
    biggest = max((e["inflated_size"] for e in entries), default=0)
    lines.append("/**")
    lines.append(" * @enum ra_book_library_scratch_t")
    lines.append(" * @brief Largest inflate scratch any bundled book needs, bytes.")
    lines.append(" * @details Size a shared open() buffer to this and every book fits.")
    lines.append(" * @since Version 1.0.0")
    lines.append(" */")
    lines.append("typedef enum : uint32_t {")
    lines.append(
        f"  k_ra_book_library_max_inflated = {biggest}U, /**< Worst-case inflated size. */"
    )
    lines.append("} ra_book_library_scratch_t;")
    lines.append("")
    lines.append("/** @brief The bundled book index. Generated; data table, magic numbers ok. */")
    lines.append("// NOLINTBEGIN(readability-magic-numbers)")
    lines.append(
        "static const ra_book_library_entry_t g_ra_book_library[k_ra_book_library_count] = {"
    )
    for e in entries:
        lines.append(
            f'    {{ "{ascii_only(e["title"])}", "{ascii_only(e["author"])}", '
            f'"{ascii_only(e["filename"])}", {e["file_size"]}U, {e["inflated_size"]}U }},'
        )
    lines.append("};")
    lines.append("// NOLINTEND(readability-magic-numbers)")
    lines.append("")

    with open(args.output, "w", encoding="ascii") as fh:
        fh.write("\n".join(lines))
    total_disk = sum(e["file_size"] for e in entries)
    print(
        f"wrote {args.output}: {len(entries)} books, "
        f"{total_disk // 1024 // 1024} MB on disk, max inflate {biggest // 1024} KB"
    )


if __name__ == "__main__":
    main()
