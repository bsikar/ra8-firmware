r"""Pin what the conv_int8_vela model must output, from host TFLite-micro.

The committed ``ra8_npu_model_conv_int8_vela.h`` is a real Vela command stream
compiled from ``conv_int8_fixture.py``, but nothing in the tree said what that
stream should produce. This script runs the fixture's plain (pre-Vela) .tflite
through the host TFLite-micro interpreter on a fixed int8 input and writes both
the input and the expected output as a Zig file a firmware example imports:

    python3 tools/vela/models/conv_int8_fixture.py build/vela/conv_int8.tflite
    python3 tools/vela/models/conv_int8_golden.py build/vela/conv_int8.tflite \\
            -o tools/vela/generated/conv_int8_vela_golden.zig

Needs the host ``tflite-micro`` wheel (pinned below); like the fixture, it is an
opt-in step outside the Vela-free gate. Every value is a fixed pattern, so two
runs write identical bytes.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

TFLM_PIN = "tflite-micro==0.dev20261002031052"
INPUT_STEP = 37
BYTE_SPAN = 256
INT8_BIAS = 128
PER_LINE = 16


def _input(count: int) -> list[int]:
    """Return the fixed int8 input pattern, ``(i * 37) mod 256 - 128``."""
    return [(i * INPUT_STEP) % BYTE_SPAN - INT8_BIAS for i in range(count)]


def _run(model: Path) -> tuple[list[int], list[int]]:
    """Run ``model`` once on the fixed input and return (input, output)."""
    try:
        import numpy as np  # noqa: PLC0415  (optional host dependency)
        from tflite_micro.python.tflite_micro import runtime  # noqa: PLC0415
    except ImportError as exc:
        sys.exit(f"conv_int8_golden: needs {TFLM_PIN} and numpy ({exc})")
    interp = runtime.Interpreter.from_file(str(model))
    shape = interp.get_input_details(0)["shape"]
    values = _input(int(np.prod(shape)))
    interp.set_input(np.array(values, dtype=np.int8).reshape(shape), 0)
    interp.invoke()
    out = interp.get_output(0).astype(np.int8).flatten().tolist()
    return values, [int(v) for v in out]


def _array(name: str, values: list[int]) -> str:
    """Render ``values`` as a public Zig ``[N]i8`` constant."""
    rows = [
        "    " + ", ".join(str(v) for v in values[i : i + PER_LINE]) + ","
        for i in range(0, len(values), PER_LINE)
    ]
    body = "\n".join(rows)
    return f"pub const {name} = [{len(values)}]i8{{\n{body}\n}};\n"


def render(values: list[int], expected: list[int]) -> str:
    """Return the whole generated Zig file."""
    head = (
        "//! SPDX-License-Identifier: MIT\n"
        "//! Copyright (c) 2026 Brighton Sikarskie\n"
        "//!\n"
        "//! GENERATED by tools/vela/models/conv_int8_golden.py. DO NOT EDIT BY HAND.\n"
        f"//! Host TFLite-micro ({TFLM_PIN}) ran conv_int8_fixture.py's model on\n"
        "//! `input`; `output` is what it produced. The Vela build of the same model\n"
        "//! (ra8_npu_model_conv_int8_vela.h) must produce the same bytes on the NPU.\n\n"
    )
    return head + _array("input", values) + "\n" + _array("output", expected)


def main(argv: list[str] | None = None) -> int:
    """Entry point: write the golden for the fixture model named on argv."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("model", type=Path, help="conv_int8_fixture.py output .tflite")
    parser.add_argument("-o", "--output", type=Path, required=True, help="Zig file to write")
    args = parser.parse_args(argv)
    values, expected = _run(args.model)
    args.output.write_text(render(values, expected), encoding="utf-8")
    print(f"conv_int8_golden: wrote {args.output} ({len(expected)} output bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
