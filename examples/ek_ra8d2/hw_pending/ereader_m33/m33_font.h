/**
 * @file examples/ek_ra8d2/hw_pending/ereader_m33/m33_font.h
 * @brief Baked 8x16 monospace bitmap font for the M33-side page render.
 *
 * @par Tag
 * [Ring1/app] {World: NS}
 *
 * @details
 * A tiny, self-contained monochrome font the Cortex-M33 image blits into the
 * shared framebuffer when it renders a page (#150). Each glyph is 8 pixels
 * wide and 16 pixels tall, stored as 16 bytes -- one byte per row, MSB on the
 * left (bit 7 is the leftmost pixel). Printable ASCII 0x20..0x7E (95 glyphs)
 * are stored back-to-back in ascending codepoint order, so the bitmap for
 * codepoint @c c starts at byte @c (c - 0x20) * 16.
 *
 * The glyph bitmaps are the public-domain IBM PC VGA character set (BIOS code
 * page 437), the same bitmaps the in-tree @c libs/ra_gfx 8x16 font carries.
 * The canonical archive states "All the original IBM-made fonts (and their
 * identical re-creations) can be considered to be in the public domain."
 * -- https://int10h.org/oldschool-pc-fonts/readme/ (retrieved 2026). The data
 * is baked directly here (not linked from ra_gfx) so the freestanding M33
 * image keeps linking nothing beyond its own code, exactly like the sibling
 * dual-core examples. Generated; do not hand-edit.
 *
 * @note The next increment may swap this compact blit for a full M33-side
 *       ra_gfx path; this baked font keeps the M33 image self-contained today.
 *
 * @copyright Copyright (c) 2026 Brighton Sikarskie
 * SPDX-License-Identifier: MIT
 * @since 0.1.0
 */
