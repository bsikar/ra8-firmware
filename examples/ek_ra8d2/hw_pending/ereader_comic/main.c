/**
 * @brief Bring up SDRAM + the GLCDC panel and bind ra8_gfx to the framebuffer.
 * @pre ::cm_bringup_clocks has run; IRQs are enabled.
 * @pre ::s_framebuffer is reachable in SDRAM.
 * @post SDRAM is up and the GLCDC scans out ::s_framebuffer.
 * @post ::s_display is non-NULL and ra8_gfx draws into the panel.
 * @note Single-shot; not thread-safe. Halts on any failure.
 * @since 0.1.0
 */
static void cm_bringup_panel(void)
{
  ra8_delay_ms((uint32_t)k_cm_settle_ms);
  if (ra8_sdramc_init() != k_ra8_ok) {
    cm_panic_halt();
  }
  if (display_init(&k_cm_display_cfg, &s_display) != k_ra8_ok) {
    cm_panic_halt();
  }
  if (display_get_framebuffer(s_display, &s_fb) != k_ra8_ok) {
    cm_panic_halt();
  }
  if (ra8_gfx_init(s_fb.pixels, s_fb.width_px, s_fb.height_px, k_ra8_gfx_format_rgb565) !=
      k_ra8_ok) {
    cm_panic_halt();
  }
}

/**
 * @brief Open the GT911 touch controller (best-effort, polled).
 * @details Brings up IIC_B in I2C-compat mode, binds it through the ra8_io
 *          facade into the driver seam, then opens the driver. Emulator runs / boards
 *          without a GT911 simply leave touch unavailable (non-fatal).
 * @pre ::cm_bringup_clocks has run (IIC_B clock + MSTP up).
 * @pre None.
 * @post On success the GT911 is configured for polled reads.
 * @post On failure touch input is simply unavailable (no panic).
 * @note Single-shot; not thread-safe.
 * @since 0.1.0
 */
static void cm_bringup_touch(void)
{
  const ra8_i3c_cfg_t iic_cfg = {
    .mode     = k_ra8_i3c_mode_i2c,
    .bus_hz   = (uint32_t)k_cm_touch_bus_hz,
    .pclka_hz = (uint32_t)k_cm_touch_pclka_hz,
  };
  if (ra8_i3c_init((uint8_t)k_cm_touch_channel, &iic_cfg) != k_ra8_ok) {
    return;
  }
  ra8_i2c_bus_ops_t bus_ops = {};
  if (ra8_io_i2c_bus_bind_i3c_compat(&s_touch_bus, (uint8_t)k_cm_touch_channel) != k_ra8_ok) {
    return;
  }
  if (ra8_io_i2c_bus_as_ops(&s_touch_bus, &bus_ops) != k_ra8_ok) {
    return;
  }
  const ra8_touch_cfg_t cfg = {
    .bus        = bus_ops,
    .target_7b  = (uint8_t)k_cm_touch_addr_7b,
    .irq_pin    = (uint8_t)k_ra8_touch_irq_pin_unset,
    .max_points = (uint8_t)k_cm_touch_max_points,
  };
  (void)ra8_touch_open(&cfg);
}

/* ===========================================================================
 * Comic reader
 * =========================================================================== */

/** @brief Read callback over the resident archive buffer. */
static size_t cm_read(void* ctx, uint64_t off, void* buf, size_t len)
{
  const cm_src_t* s = (const cm_src_t*)ctx;
  if (off >= (uint64_t)s->n) {
    return 0U;
  }
  const uint64_t avail = (uint64_t)s->n - off;
  const size_t   k     = (len > (size_t)avail) ? (size_t)avail : len;
  (void)memcpy(buf, &s->d[off], k);
  return k;
}

/**
 * @brief Open the baked CBZ once and cache its page count.
 * @return Whether the archive opened with at least one page.
 * @retval true  ::s_comic is open and ::s_page_count is set (>= 1).
 * @retval false The archive failed to open.
 * @pre ::k_comic_cbz holds ::k_comic_cbz_len readable bytes.
 * @pre ::s_comic is zero-initialised.
 * @post On true the reader stays open for the app lifetime.
 * @post On false ::s_comic is left in the unopened state.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static bool cm_open_comic(void)
{
  s_src.d = k_comic_cbz;
  s_src.n = (size_t)k_comic_cbz_len;
  if (ra8_comic_open(&s_comic,
                     cm_read,
                     &s_src,
                     (uint64_t)k_comic_cbz_len,
                     s_pages,
                     (uint32_t)k_cm_page_cap,
                     s_names,
                     (uint32_t)sizeof(s_names)) != k_ra8_ok) {
    return false;
  }
  s_page_count = ra8_comic_page_count(&s_comic);
  return (s_page_count >= 1U);
}

/* ===========================================================================
 * Rendering
 * =========================================================================== */

/**
 * @brief Decode the current page and aspect-fit it into the content region.
 * @return Whether the page decoded and blitted.
 * @retval true  ::s_page was drawn into the content box.
 * @retval false Extract or decode failed (box left as letterbox).
 * @pre ra8_gfx is bound; ::s_comic is open; ::s_page < ::s_page_count.
 * @pre The content region has been cleared to the letterbox colour.
 * @post On true the page image occupies the content region.
 * @post ::s_img_arena is reset to empty on every return.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static bool cm_draw_page(void)
{
  size_t got = 0U;
  if (ra8_comic_page_read(&s_comic, s_page, s_pagebuf, sizeof(s_pagebuf), &got) != k_ra8_ok) {
    return false;
  }
  ra8_img_arena_t arena = {.base = s_img_arena, .cap = (size_t)k_cm_arena_bytes};
  const int32_t   box_y = (int32_t)k_cm_statusbar_h;
  const int32_t   box_h = (int32_t)k_cm_fb_h - (int32_t)k_cm_statusbar_h - (int32_t)k_cm_progress_h;
  return (ra8_img_decode_blit(&arena,
                              s_pagebuf,
                              got,
                              0,
                              box_y,
                              (int32_t)k_cm_fb_w,
                              box_h,
                              nullptr,
                              nullptr) == k_ra8_ok);
}

/**
 * @brief Draw the top status bar: title, ``Page N of M``, battery percent.
 * @pre ra8_gfx is bound; ::s_page_count >= 1.
 * @pre ::s_page < ::s_page_count.
 * @post The status band holds the title / position / battery text.
 * @post No reader state is mutated.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static void cm_draw_status_bar(void)
{
  (void)ra8_gfx_rect(0,
                     0,
                     (int32_t)k_cm_fb_w,
                     (int32_t)k_cm_statusbar_h,
                     (uint32_t)k_cm_col_bar_bg,
                     true);
  const int32_t ty = ((int32_t)k_cm_statusbar_h - (int32_t)k_cm_glyph_h) / 2;
  (void)ra8_gfx_text_out((int32_t)k_cm_text_pad,
                         ty,
                         k_cm_title,
                         &ra8_gfx_font_8x16,
                         (uint32_t)k_cm_col_bar_fg,
                         (uint32_t)k_cm_col_bar_bg);

  char     pos[k_cm_pos_cap];
  char     num[k_cm_dec_ten];
  uint32_t cur = 0U;
  (void)cm_utoa(s_page + 1U, num, (uint32_t)sizeof(num));
  cm_append(pos, (uint32_t)sizeof(pos), &cur, k_cm_pos_prefix);
  cm_append(pos, (uint32_t)sizeof(pos), &cur, num);
  cm_append(pos, (uint32_t)sizeof(pos), &cur, k_cm_pos_infix);
  (void)cm_utoa(s_page_count, num, (uint32_t)sizeof(num));
  cm_append(pos, (uint32_t)sizeof(pos), &cur, num);
  const int32_t pos_x = ((int32_t)k_cm_fb_w / 2) - (((int32_t)cur * (int32_t)k_cm_glyph_w) / 2);
  (void)ra8_gfx_text_out(pos_x,
                         ty,
                         pos,
                         &ra8_gfx_font_8x16,
                         (uint32_t)k_cm_col_bar_fg,
                         (uint32_t)k_cm_col_bar_bg);

  char     batt[k_cm_batt_cap];
  uint32_t bl   = cm_utoa((uint32_t)k_cm_batt_pct, batt, (uint32_t)sizeof(batt));
  batt[bl]      = '%';
  batt[bl + 1U] = '\0';
  bl++;
  const int32_t bx =
    (int32_t)k_cm_fb_w - (int32_t)k_cm_text_pad - ((int32_t)bl * (int32_t)k_cm_glyph_w);
  (void)ra8_gfx_text_out(bx,
                         ty,
                         batt,
                         &ra8_gfx_font_8x16,
                         (uint32_t)k_cm_col_bar_muted,
                         (uint32_t)k_cm_col_bar_bg);
}

/**
 * @brief Draw the bottom progress bar (filled fraction = read position).
 * @pre ra8_gfx is bound; ::s_page_count >= 1.
 * @pre ::s_page < ::s_page_count.
 * @post The progress band holds the track + accent fill.
 * @post No reader state is mutated.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static void cm_draw_progress_bar(void)
{
  const int32_t band_y = (int32_t)k_cm_fb_h - (int32_t)k_cm_progress_h;
  (void)ra8_gfx_rect(0,
                     band_y,
                     (int32_t)k_cm_fb_w,
                     (int32_t)k_cm_progress_h,
                     (uint32_t)k_cm_col_bar_bg,
                     true);
  const int32_t tx = (int32_t)k_cm_track_inset;
  const int32_t tw = (int32_t)k_cm_fb_w - (2 * (int32_t)k_cm_track_inset);
  const int32_t th = (int32_t)k_cm_track_h;
  const int32_t ty = band_y + (((int32_t)k_cm_progress_h - th) / 2);
  (void)ra8_gfx_rect(tx, ty, tw, th, (uint32_t)k_cm_col_track, true);
  const int32_t fw = (int32_t)(((int64_t)tw * (int64_t)(s_page + 1U)) / (int64_t)s_page_count);
  (void)ra8_gfx_rect(tx, ty, fw, th, (uint32_t)k_cm_col_fill, true);
}

/**
 * @brief Render the whole reader screen: letterbox, page, and optional chrome.
 * @pre ra8_gfx is bound; ::s_comic is open.
 * @pre ::s_page < ::s_page_count.
 * @post The framebuffer holds the current page (+ chrome when enabled).
 * @post No navigation state is mutated.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static void cm_render(void)
{
  (void)ra8_gfx_clear((uint32_t)k_cm_col_letterbox);
  (void)cm_draw_page();
  if (s_chrome_on) {
    cm_draw_status_bar();
    cm_draw_progress_bar();
  }
}

/** @brief Flush the whole panel so the GLCDC scans out the new frame. */
static void cm_present(void)
{
  (void)display_flush(s_display, display_full_rect(s_display), k_display_refresh_quality);
}

/* ===========================================================================
 * Tap-zone navigation
 * =========================================================================== */

/**
 * @brief Classify a panel touch into a navigation zone.
 * @param[in] x Panel X (0 .. width-1).
 * @param[in] y Panel Y (0 .. height-1).
 * @return The ::cm_zone_t the coordinate falls in.
 * @retval k_cm_zone_prev   Left third.
 * @retval k_cm_zone_next   Right third.
 * @retval k_cm_zone_chrome Center column, top half.
 * @retval k_cm_zone_none   Center column, bottom half.
 * @pre 0 <= @p x < ::k_cm_fb_w.
 * @pre 0 <= @p y < ::k_cm_fb_h.
 * @post No state is mutated (pure).
 * @post Exactly one zone is returned.
 * @note Pure; thread-safe.
 * @since 0.1.0
 */
static cm_zone_t cm_zone_at(int32_t x, int32_t y)
{
  const int32_t third = (int32_t)k_cm_fb_w / (int32_t)k_cm_thirds;
  if (x < third) {
    return k_cm_zone_prev;
  }
  if (x >= (2 * third)) {
    return k_cm_zone_next;
  }
  if (y < ((int32_t)k_cm_fb_h / (int32_t)k_cm_halves)) {
    return k_cm_zone_chrome;
  }
  return k_cm_zone_none;
}

/**
 * @brief Apply a tap: turn a page or toggle the chrome.
 * @param[in] x Panel X of the tap.
 * @param[in] y Panel Y of the tap.
 * @return Whether the tap changed what is shown (caller must re-render).
 * @retval true  A page turned or the chrome toggled.
 * @retval false The tap was a no-op (already at an end, or dead zone).
 * @pre ::s_comic is open; ::s_page_count >= 1.
 * @pre 0 <= @p x < ::k_cm_fb_w and 0 <= @p y < ::k_cm_fb_h.
 * @post On true ::s_page or ::s_chrome_on reflects the tap.
 * @post On false no state is mutated.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static bool cm_handle_tap(int32_t x, int32_t y)
{
  switch (cm_zone_at(x, y)) {
    case k_cm_zone_next:
      if ((s_page + 1U) < s_page_count) {
        s_page++;
        return true;
      }
      return false;
    case k_cm_zone_prev:
      if (s_page > 0U) {
        s_page--;
        return true;
      }
      return false;
    case k_cm_zone_chrome:
      s_chrome_on = !s_chrome_on;
      return true;
    case k_cm_zone_none:
    default:
      return false;
  }
}

/**
 * @brief Poll the GT911 once and dispatch a tap on a fresh press.
 * @pre ra8_gfx bound; ::s_display valid; ::s_comic open.
 * @pre None.
 * @post On a fresh press that changes state, the panel is re-rendered + flushed.
 * @post ::s_was_touching tracks the contact state.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static void cm_poll_touch(void)
{
  ra8_touch_point_t pt  = {};
  uint8_t           got = 0U;
  if (ra8_touch_read(&pt, (uint8_t)k_cm_touch_max_points, &got) != k_ra8_ok) {
    return;
  }
  const bool touching = (got > 0U);
  if (touching && !s_was_touching) {
    if (cm_handle_tap((int32_t)pt.x, (int32_t)pt.y)) {
      cm_render();
      cm_present();
    }
  }
  s_was_touching = touching;
}

/**
 * @brief Print the deterministic boot banner (page-1 framebuffer hash).
 * @pre ::cm_render + ::cm_present have drawn page 1 to the framebuffer.
 * @pre The console is initialised.
 * @post One banner line is emitted over SCI8.
 * @post No reader state is mutated.
 * @note Not thread-safe.
 * @since 0.1.0
 */
static void cm_print_banner(void)
{
  cm_print(k_cm_msg_pre, (uint32_t)sizeof(k_cm_msg_pre) - 1U);
  cm_print_uint(s_page_count);
  cm_print(k_cm_msg_dim, (uint32_t)sizeof(k_cm_msg_dim) - 1U);
  cm_print_uint((uint32_t)k_cm_fb_w);
  cm_print(k_cm_msg_x, (uint32_t)sizeof(k_cm_msg_x) - 1U);
  cm_print_uint((uint32_t)k_cm_fb_h);
  cm_print(k_cm_msg_page, (uint32_t)sizeof(k_cm_msg_page) - 1U);
  cm_print_hex(cm_framebuffer_hash());
  cm_print(k_cm_msg_tiled, (uint32_t)sizeof(k_cm_msg_tiled) - 1U);
  cm_print_uint(s_tiled.w);
  cm_print(k_cm_msg_x, (uint32_t)sizeof(k_cm_msg_x) - 1U);
  cm_print_uint(s_tiled.h);
  cm_print(k_cm_msg_colon, (uint32_t)sizeof(k_cm_msg_colon) - 1U);
  cm_print_uint(s_tiled.tiles);
  cm_print(k_cm_msg_colon, (uint32_t)sizeof(k_cm_msg_colon) - 1U);
  cm_print_hex(s_tiled.crc);
  cm_print(k_cm_msg_ok, (uint32_t)sizeof(k_cm_msg_ok) - 1U);
}

#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wmain"
/**
 * @brief App entry: bring up the panel, open the comic, render + poll taps.
 * @return Never returns.
 * @pre Reset_Handler copied .data and zeroed .bss.
 * @pre SystemInit set VTOR / FPU / priority grouping.
 * @post The reader loop runs forever, redrawing on each tap.
 * @post A page-1 banner is emitted once after the first render.
 * @since 0.1.0
 */
int32_t main(void)
{
  cm_bringup_clocks();
  cm_print(k_cm_msg_boot, (uint32_t)sizeof(k_cm_msg_boot) - 1U);
  cm_bringup_panel();
  cm_bringup_touch();

  if (!cm_open_comic()) {
    cm_print(k_cm_msg_cerr, (uint32_t)sizeof(k_cm_msg_cerr) - 1U);
    cm_panic_halt();
  }

  cm_render();
  cm_present();
  s_tiled = cm_comic_tiled_selfcheck();
  cm_print_banner();

  while (1) {
    cm_poll_touch();
    if ((s_loop_ticks % (uint32_t)k_cm_led_every) == 0U) {
      (void)ra8_board_led_toggle(k_ra8_board_led_blue);
    }
    s_loop_ticks++;
    ra8_delay_ms((uint32_t)k_cm_frame_ms);
  }
  return 0;
}
