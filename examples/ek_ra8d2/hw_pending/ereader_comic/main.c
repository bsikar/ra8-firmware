/**
 * @brief Halt forever with the red board LED on (fatal init error).
 * @return Never returns.
 * @pre None.
 * @pre None.
 * @post Function never returns; CPU parked in WFI.
 * @post Red LED is on.
 * @note IRQ-safe.
 * @since 0.1.0
 */
[[noreturn]] static void cm_panic_halt(void)
{
  (void)ra8_board_led_on(k_ra8_board_led_red);
  while (1) {
    __asm__ volatile("wfi");
  }
}

/**
 * @brief Bring up clocks, MSTP, SysTick, the console, and both board LEDs.
 * @pre Reset_Handler ran .data/.bss init; IRQs are globally disabled.
 * @pre ::ra8_cgc_init has not yet run.
 * @post Clocks, MSTP, ra8_time, console, and LEDs are initialised.
 * @post Global IRQs are enabled.
 * @note Single-shot; not thread-safe. Halts on any failure.
 * @since 0.1.0
 */
static void cm_bringup_clocks(void)
{
  uint32_t cpuclk0_hz = 0U;
  if ((ra8_cgc_init() != k_ra8_ok) || (ra8_mstp_init() != k_ra8_ok)) {
    cm_panic_halt();
  }
  if (ra8_cgc_get_clock_hz(k_ra8_clock_id_cpuclk0, &cpuclk0_hz) != k_ra8_ok) {
    cm_panic_halt();
  }
  if (ra8_time_init(cpuclk0_hz) != k_ra8_ok) {
    cm_panic_halt();
  }
  if (ra8_board_uart_console_init((uint32_t)k_cm_uart_baud) != k_ra8_ok) {
    cm_panic_halt();
  }
  if ((ra8_board_led_init(k_ra8_board_led_blue) != k_ra8_ok) ||
      (ra8_board_led_init(k_ra8_board_led_red) != k_ra8_ok)) {
    cm_panic_halt();
  }
  ra8_isr_globals_enable();
}

