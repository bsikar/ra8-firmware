/** @brief Emit a byte run on the SCI8 console. */
static void cm_print(const uint8_t* msg, uint32_t len)
{
  (void)ra8_board_uart_console_write(msg, (size_t)len);
}

/** @brief Print a 32-bit value as 8 upper-case hex digits. */
static void cm_print_hex(uint32_t value)
{
  uint8_t buf[k_cm_hex_nibbles];
  for (uint32_t i = 0U; i < (uint32_t)k_cm_hex_nibbles; i++) {
    const uint32_t shift = ((uint32_t)k_cm_hex_nibbles - 1U - i) * (uint32_t)k_cm_nibble_bits;
    const uint32_t nib   = (value >> shift) & (uint32_t)k_cm_nibble_mask;
    buf[i] = (uint8_t)((nib < (uint32_t)k_cm_dec_ten) ? ('0' + nib) : ('A' + (nib - k_cm_dec_ten)));
  }
  cm_print(buf, (uint32_t)k_cm_hex_nibbles);
}

/** @brief Print a small unsigned integer in decimal. */
static void cm_print_uint(uint32_t value)
{
  uint8_t  buf[k_cm_dec_ten];
  uint32_t n = 0U;
  if (value == 0U) {
    buf[n] = '0';
    n++;
  }
  while ((value > 0U) && (n < (uint32_t)k_cm_dec_ten)) {
    buf[n] = (uint8_t)('0' + (value % (uint32_t)k_cm_dec_ten));
    n++;
    value /= (uint32_t)k_cm_dec_ten;
  }
  for (uint32_t i = 0U; i < n; i++) {
    cm_print(&buf[n - 1U - i], 1U);
  }
}

/**
 * @brief Format a small unsigned into a caller ASCII buffer, NUL-terminated.
 * @param[in]  value Value to format (0 .. 9999999999).
 * @param[out] buf   Destination (>= 2 bytes, holds the digits + NUL).
 * @param[in]  cap   Capacity of @p buf in bytes (>= 2).
 * @return The number of digit characters written (excluding the NUL).
 * @retval count Digits emitted (>= 1).
 * @pre @p buf holds @p cap writable bytes.
 * @pre @p cap >= 2.
 * @post @p buf is NUL-terminated within @p cap.
 * @post The return value equals the digit length.
 * @note Pure formatting helper; not thread-safe on shared buffers.
 * @since 0.1.0
 */
static uint32_t cm_utoa(uint32_t value, char* buf, uint32_t cap)
{
  char     tmp[k_cm_dec_ten];
  uint32_t n = 0U;
  if (value == 0U) {
    tmp[n] = '0';
    n++;
  }
  while ((value > 0U) && (n < (uint32_t)k_cm_dec_ten)) {
    tmp[n] = (char)('0' + (value % (uint32_t)k_cm_dec_ten));
    n++;
    value /= (uint32_t)k_cm_dec_ten;
  }
  uint32_t o = 0U;
  while ((n > 0U) && (o < (cap - 1U))) {
    n--;
    buf[o] = tmp[n];
    o++;
  }
  buf[o] = '\0';
  return o;
}

/**
 * @brief Append a NUL-terminated string into a bounded buffer at @p *cursor.
 * @param[in,out] dst    Destination buffer (NUL-terminated on return).
 * @param[in]     cap    Capacity of @p dst in bytes.
 * @param[in,out] cursor Current write offset; advanced past the copy.
 * @param[in]     src    Source string (NUL-terminated).
 * @pre @p dst holds @p cap writable bytes and @p *cursor < @p cap.
 * @pre @p src is a valid NUL-terminated string.
 * @post @p dst[*cursor] == '\0' and @p *cursor <= @p cap - 1.
 * @post No write occurs past @p cap - 1.
 * @note Not thread-safe on a shared buffer.
 * @since 0.1.0
 */
static void cm_append(char* dst, uint32_t cap, uint32_t* cursor, const char* src)
{
  uint32_t o = *cursor;
  for (uint32_t j = 0U; (src[j] != '\0') && (o < (cap - 1U)); j++) {
    dst[o] = src[j];
    o++;
  }
  dst[o]  = '\0';
  *cursor = o;
}

/** @brief FNV-1a-32 over the whole panel framebuffer (deterministic banner). */
static uint32_t cm_framebuffer_hash(void)
{
  const uint8_t* p   = (const uint8_t*)s_framebuffer;
  const size_t   nby = sizeof(s_framebuffer);
  uint32_t       hsh = (uint32_t)k_cm_fnv_offset;
  for (size_t i = 0U; i < nby; i++) {
    hsh = (hsh ^ (uint32_t)p[i]) * (uint32_t)k_cm_fnv_prime;
  }
  return hsh;
}

