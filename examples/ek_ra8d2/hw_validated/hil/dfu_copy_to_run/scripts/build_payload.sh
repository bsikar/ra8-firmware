# build_payload.sh -- build the copy-to-run demo payload.
#
# Produces ONE position-fixed image (linked at the SRAM run base
# k_ra8_dfu_run_base = 0x22020000) that a copy-to-run launcher copies to SRAM and
# runs, so the same .bin runs wherever it was staged (issue #97). Integer-only
# and freestanding, so -mfloat-abi=soft links with no libc/libm.
#
# Also (re)generates inc/payload_image.h -- the committed C-array form of
# payload.bin that src/main.c launches via ra8_dfu_launch. Re-run this whenever
# src/payload.c changes, and commit the refreshed header.
#
# Usage: examples/ek_ra8d2/hw_validated/hil/dfu_copy_to_run/scripts/build_payload.sh [out.bin]
# Default output: payload.bin at the app root.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CC="${ARM_CC:-arm-none-eabi-gcc}"
OBJCOPY="${ARM_OBJCOPY:-arm-none-eabi-objcopy}"
OUT="${1:-$APP_DIR/payload.bin}"
ELF="${OUT%.bin}.elf"
HDR="$APP_DIR/inc/payload_image.h"

"$CC" -mcpu=cortex-m85 -mthumb -mfloat-abi=soft \
  -std=c2x -Os -ffreestanding -nostdlib -nostartfiles \
  -ffunction-sections -fdata-sections \
  -Wall -Wextra -Werror \
  -T "$APP_DIR/payload.ld" -o "$ELF" "$APP_DIR/src/payload.c"
"$OBJCOPY" -O binary "$ELF" "$OUT"

# Emit the committed C-array header the demo embeds (single source: src/payload.c).
python3 - "$OUT" "$HDR" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w", encoding="ascii") as h:
    h.write("/**\n")
    h.write(" * @file inc/payload_image.h\n")
    h.write(" * @brief GENERATED by examples/ek_ra8d2/hw_validated/hil/dfu_copy_to_run/scripts/\n")
    h.write(" * build_payload.sh from src/payload.c -- do not edit.\n")
    h.write(" * @details The copy-to-run demo payload (linked at k_ra8_dfu_run_base) as a\n")
    h.write(" *          byte array, embedded by main.c and launched via ra8_dfu_launch.\n")
    h.write(" *          Re-run examples/ek_ra8d2/hw_validated/hil/dfu_copy_to_run/scripts/\n")
    h.write(" *          build_payload.sh and commit this file when needed.\n")
    h.write(" * @copyright Copyright (c) 2026 Brighton Sikarskie\n")
    h.write(" * SPDX-License-Identifier: MIT\n")
    h.write(" */\n\n")
    h.write("#pragma once\n\n")
    h.write("#include <stdint.h>\n\n")
    h.write("/** @brief Copy-to-run demo payload image (vector table + reset stub). */\n")
    h.write(f"alignas(4) static const uint8_t s_payload_image[{len(data)}] = {{\n")
    for i in range(0, len(data), 16):
        row = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        h.write(f"  {row},\n")
    h.write("};\n")
PY

# Canonicalise to the project clang-format style when the tool is available, so
# the committed payload_image.h passes `just quality::local::check` regardless of the row width.
if command -v clang-format >/dev/null 2>&1; then
  clang-format -i "$HDR"
fi

size_bytes="$(wc -c <"$OUT" | tr -d ' ')"
echo "payload: $OUT (${size_bytes} bytes), elf: $ELF, header: $HDR"
echo "stage it:  python3 $APP_DIR/../dfu_bootloader/scripts/stage_slot_image.py --payload $OUT --slot a --out slotA.hex"
