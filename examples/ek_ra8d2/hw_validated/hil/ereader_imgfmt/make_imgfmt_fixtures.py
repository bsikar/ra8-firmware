# Generate imgfmt_fixtures.h: small deterministic BMP and GIF test images for
# the ereader_imgfmt gate -- the last two stb_image formats the firmware
# links (STBI_ONLY_BMP / STBI_ONLY_GIF) that lacked an example. PNG and JPEG
# already have ereader_image / ereader_jpeg.
#
# Each image is a 40x30 four-quadrant pattern; the on-device gate decodes both
# through ra8_img_decode_blit (zero-heap) into a 160x120 framebuffer and CRC-
# gates each. Output is pure 7-bit ASCII, baked at 16 bytes per row so
# clang-format leaves it byte-identical.
#
# Usage:  python3 make_imgfmt_fixtures.py
import io
from pathlib import Path

from PIL import Image

W, H = 40, 30
QUAD = [(0xC0, 0x10, 0x20), (0x18, 0x90, 0x30), (0x20, 0x40, 0xC0), (0xD0, 0xA0, 0x18)]


def make_image(layout: str) -> Image.Image:
    # Two distinct patterns so the BMP and GIF decode to different pixels and
    # therefore pin two different CRCs (each path independently gated).
    img = Image.new("RGB", (W, H))
    px = img.load()
    for y in range(H):
        for x in range(W):
            if layout == "quad":
                idx = (1 if x >= W // 2 else 0) + (2 if y >= H // 2 else 0)
            else:  # horizontal bands
                idx = min(y // (H // len(QUAD)), len(QUAD) - 1)
            px[x, y] = QUAD[idx]
    return img


def encode(fmt: str) -> bytes:
    # BMP gets the quadrant layout; GIF gets horizontal bands.
    img = make_image("quad" if fmt == "BMP" else "bands")
    out = io.BytesIO()
    if fmt == "GIF":
        # Palette mode keeps the GIF tiny and deterministic.
        img = img.convert("P", palette=Image.ADAPTIVE, colors=4)
    img.save(out, format=fmt)
    return out.getvalue()


def bake_array(name: str, data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        rows.append("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    body = "\n".join(rows)
    return (
        f"/** @brief Length of the baked {name.upper()} image, bytes. */\n"
        f"enum : size_t {{ k_{name}_len = {len(data)}U }};\n"
        "\n"
        f"/** @brief Baked 40x30 four-quadrant {name.upper()} image. */\n"
        "/* clang-format off */\n"
        f"static const uint8_t k_{name}[k_{name}_len] = {{\n"
        f"{body}\n"
        "};\n"
        "/* clang-format on */\n"
    )


def main():
    bmp = encode("BMP")
    gif = encode("GIF")
    header = (
        "/**\n"
        " * @file imgfmt_fixtures.h\n"
        " * @brief Baked BMP + GIF test images for the ereader_imgfmt gate.\n"
        " *\n"
        " * @details The two stb_image formats (STBI_ONLY_BMP / STBI_ONLY_GIF) that\n"
        " * had no example. Each is a 40x30 four-quadrant image, byte-identical run to\n"
        " * run. Generated by make_imgfmt_fixtures.py. Pure ASCII, 16 bytes per row.\n"
        " *\n"
        " * @copyright Copyright (c) 2026 Brighton Sikarskie\n"
        " * SPDX-License-Identifier: MIT\n"
        " */\n"
        "#pragma once\n"
        "\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "\n"
        f"{bake_array('bmp', bmp)}"
        "\n"
        f"{bake_array('gif', gif)}"
    )
    with Path("imgfmt_fixtures.h").open("w", encoding="ascii") as f:
        f.write(header)
    print(f"wrote imgfmt_fixtures.h (bmp {len(bmp)} B, gif {len(gif)} B)")


if __name__ == "__main__":
    main()
