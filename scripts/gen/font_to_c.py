"""Emit a C source file embedding a binary font blob as a byte array.

Dependency-free (stdlib only) so it runs at build time on any host without a
venv. The generated .c is written to the build directory and is NOT committed,
which keeps the large hex array out of the QC gates (magic-numbers / format).

Usage:
  font_to_c.py <input-font> <output.c> <symbol_name> <header_name>

The output defines, against the declarations in <header_name> (one header per
baked font, named after the font -- e.g. literata_latin1.h):
  const unsigned char <symbol_name>[]  = { ... };
  const unsigned int  <symbol_name>_len = <N>;

Which codepoints each baked subset carries is declared in
.github/font-coverage-declaration.txt and gated by
scripts/checks/check_font_coverage.py, which reads the committed .ttf cmap back
and fails on drift in either direction. Do not trust a recipe written here: the
one this docstring used to carry asked for 0020-00FF, which is 33 codepoints
wider than the file it claimed to describe (the unencoded C1 block, 007F-009F,
is not in the subset). Ask the checker for the arguments that really reproduce
the committed bytes:
  python3 scripts/checks/check_font_coverage.py --recipe

The Latin-1 subset checked in at libs/ra8_fonts/literata_latin1.ttf was cut
with fonttools (in a throwaway venv) from libs/ra8_fonts/Literata-Regular.ttf
(Literata Regular, SIL OFL 1.1, googlefonts/literata):
  pyftsubset Literata-Regular.ttf \
    --unicodes="$(python3 scripts/checks/check_font_coverage.py --recipe)" \
    --output-file=literata_latin1.ttf \
    --no-hinting --desubroutinize --glyph-names --notdef-outline
(--recipe prints 'libs/ra8_fonts/literata_latin1.ttf: --unicodes=...'; pass the
range list, and widen the declaration first when the intent is more coverage.)

Copyright (c) 2026 Brighton Sikarskie
SPDX-License-Identifier: MIT
"""

import pathlib
import sys

# Expected number of CLI arguments: script + 4 positional args.
EXPECTED_ARGC = 5


def main() -> int:
    """Convert a font file to a C array, or exit 2 on a usage error.

    Rejects an EMPTY input rather than emitting a zero-length array: a
    zero-length font links cleanly and fails only at render time, where the
    cause is far from the effect.

    Returns 0 on success, 2 on wrong argument count.
    """
    if len(sys.argv) != EXPECTED_ARGC:
        sys.stderr.write(
            "usage: font_to_c.py <input-font> <output.c> <symbol_name> <header_name>\n"
        )
        return 2
    src, dst, name, header = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
    data = pathlib.Path(src).read_bytes()
    if not data:
        sys.stderr.write(f"font_to_c.py: empty input {src}\n")
        return 1

    out = []
    out.append("/* GENERATED by scripts/gen/font_to_c.py -- do not edit. */")
    out.append(f"/* Source: {pathlib.Path(src).name} ({len(data)} bytes). */")
    out.append(f'#include "{header}"')
    out.append("")
    out.append(f"const unsigned char {name}[] = {{")
    # 16 bytes per line keeps the file readable; it is build-only, not committed.
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        out.append("  " + "".join(f"0x{b:02X}, " for b in chunk).rstrip())
    out.append("};")
    out.append(f"const unsigned int {name}_len = {len(data)}U;")
    out.append("")

    pathlib.Path(dst).write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
