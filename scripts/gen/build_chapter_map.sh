# build_chapter_map.sh -- Build docs/reference/CHAPTER_MAP.md from the
# Renesas RA8D2 Hardware User's Manual table of contents.
#
# Strategy: run pdftotext -layout over the TOC page range in the tracked full
# manual (PDF pages 10..67, rev 1.30, Feb 2026),
# then extract top-level chapter headings (lines that start with
# "<digit>+. <heading>"). The result is a deterministic, page-cited
# chapter map that cite_check.py validates HUM annotations against.
#
# Hand-verification pass: open the rendered TOC pages directly via the
# Read tool when adding driver-level subsection citations -- pdftotext
# can mangle two-column register tables, but the chapter list is
# stable.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PDF_FILE="$REPO_ROOT/docs/reference/ra8d2-hardware-user-manual.pdf"
OUT_FILE="$REPO_ROOT/docs/reference/CHAPTER_MAP.md"

if [[ $# -gt 0 ]]; then
  if [[ $# -ne 2 || $1 != "--output" || -z $2 ]]; then
    echo "usage: $0 [--output PATH]" >&2
    exit 2
  fi
  OUT_FILE=$2
fi

TOC_FIRST_PAGE=10
TOC_LAST_PAGE=67

if [[ ! -f "$PDF_FILE" ]]; then
  echo "ERROR: tracked full HUM PDF not found: $PDF_FILE" >&2
  exit 1
fi

if ! command -v pdftotext >/dev/null 2>&1; then
  echo "ERROR: pdftotext not found (install poppler-utils)" >&2
  exit 1
fi

tmp_raw=$(mktemp)
tmp_chapters=$(mktemp)
trap 'rm -f "$tmp_raw" "$tmp_chapters"' EXIT

pdftotext -f "$TOC_FIRST_PAGE" -l "$TOC_LAST_PAGE" -layout "$PDF_FILE" - \
  2>/dev/null >"$tmp_raw"

python3 - "$tmp_raw" "$tmp_chapters" <<'PYEOF'
import re
import sys

raw_path = sys.argv[1]
out_path = sys.argv[2]

# Top-level chapter headings look like:
# "1. Overview ............ 69"
# "53. 16-bit A/D Converter (ADC16H) ........ 3308"
# Leading whitespace is allowed because pdftotext preserves layout.
top_re = re.compile(r"^\s*(\d{1,2})\.\s+([^\.]+?)\s+\.{2,}\s*(\d{1,5})\s*$")

# Some chapters have a missing dot leader because pdftotext drops them
# under certain layouts -- fall back to "<num>. <text> <pageno>".
loose_re = re.compile(r"^\s*(\d{1,2})\.\s+(.+?)\s+(\d{2,5})\s*$")

chapters = {}
with open(raw_path, "r", encoding="utf-8", errors="replace") as fh:
    for line in fh:
        m = top_re.match(line)
        if m is None:
            m = loose_re.match(line)
        if m is None:
            continue
        num = int(m.group(1))
        title = " ".join(m.group(2).strip().rstrip(".").split())
        page = int(m.group(3))
        # First occurrence wins -- the TOC lists each chapter once.
        if num not in chapters and 1 <= num <= 99:
            chapters[num] = (title, page)

with open(out_path, "w", encoding="utf-8") as out:
    for num in sorted(chapters):
        title, page = chapters[num]
        out.write(f"{num}\t{title}\t{page}\n")
PYEOF

# Build the markdown output. End-page is computed as the next chapter's
# start page minus one. The last chapter ends at the manual's tail page.
LAST_PAGE=4291

python3 - "$tmp_chapters" "$OUT_FILE" "$LAST_PAGE" <<'PYEOF'
import sys

src = sys.argv[1]
dst = sys.argv[2]
last_page = int(sys.argv[3])

rows = []
with open(src, "r", encoding="utf-8") as fh:
    for line in fh:
        num_s, title, page_s = line.rstrip("\n").split("\t")
        rows.append((int(num_s), title, int(page_s)))

rows.sort(key=lambda r: r[0])

md = []
md.append("# RA8D2 Hardware User's Manual -- Chapter Map")
md.append("")
md.append("Source document: docs/reference/ra8d2-hardware-user-manual.pdf (Rev. 1.30, Feb 2026)")
md.append("")
md.append("Total PDF pages: 4291")
md.append("")
md.append("This file is the page-range source of truth for HUM citations.")
md.append("Generated by `scripts/gen/build_chapter_map.sh`. Citations in")
md.append("source code use the form")
md.append("`/* HUM Ch X.Y \"section name\", p NNNN */` and are validated by")
md.append("`scripts/checks/cite_check.py` against the page ranges below.")
md.append("")
md.append("Page numbers below are PDF page numbers, which match the printed")
md.append("page numbers in this manual revision.")
md.append("")
md.append("## Chapters")
md.append("")
md.append("| Ch | Title | Start | End |")
md.append("|---:|-------|------:|----:|")

for i, (num, title, start) in enumerate(rows):
    if i + 1 < len(rows):
        end = rows[i + 1][2] - 1
    else:
        end = last_page
    safe_title = title.replace("|", "\\|")
    md.append(f"| {num} | {safe_title} | {start} | {end} |")

md.append("")
md.append("## Security / TrustZone reference index")
md.append("")
md.append("The TrustZone partitioning work leans on the following")
md.append("HUM chapters. Each entry is hand-verified against the rendered TOC")
md.append("pages and the chapter body via the Read tool, not just pdftotext.")
md.append("")
md.append("- **SAU / IDAU and Armv8-M security extension**")
md.append(" - Ch 2 \"CPU\", subsection 2.3 \"Implementation Options\" -- declares Armv8-M Security Extension and the Cortex-M85 PMSAv8 / Secure MPU layout.")
md.append(" - Ch 16 \"Memory Protection Unit (MPU)\" -- Secure MPU (MPU_S) and Non-Secure MPU (MPU_NS) region rules; this is where `system_init.c` writes its SAU regions in tandem with the CPU's PMSAv8.")
md.append("- **Per-peripheral security attribution registers**")
md.append(" - Ch 6 \"Resets\", register 6.2.1 `RSTSAR` (Reset Security Attribution Register).")
md.append(" - Ch 8 \"Programmable Voltage Detection (PVD)\", register 8.2.1 `PVDSAR`.")
md.append(" - Ch 9 \"Clock Generation Circuit\", register 9.2.1 `CGFSAR` (Clock Generation Function Security Attribute Register).")
md.append(" - Ch 3 \"Inter-Processor Communication (IPC)\", registers 3.2.1 `IPCSAR` / 3.2.2 `IPCPAR`.")
md.append(" - Each peripheral chapter (SCI, IIC, SPI, GPT, ADC, CRC, USB, ETH, GLCDC, ...) carries its own `xxxSAR` register near the head of its register description block; cite_check picks these up by chapter rather than by exhaustive listing.")
md.append("- **Memory map and address-space partitioning**")
md.append(" - Ch 5 \"Address Space\", subsections 5.1 \"Address Space\", 5.2 \"External Address Space\", 5.3 \"Peripheral I/O Register Address Space\" -- the canonical Secure / Non-Secure address split lives here.")
md.append(" - Ch 15 \"Buses\" -- bus initiator security attribution and the bus-side filters that back the per-peripheral SAR registers.")
md.append(" - Ch 58 \"SRAM\" and Ch 59 \"MRAM\" -- the Secure / Non-Secure halves of MRAM and the SRAM-0 / SRAM-1 split that the linker script consumes.")
md.append(" - Ch 7 \"Option-Setting Memory\" -- FSBL secure boot path, anti-rollback counters, OEM root-key hashes; the boot trust anchor for the Secure world.")
md.append("- **NSC veneer placement**")
md.append(" - Ch 2 \"CPU\", subsection 2.3 \"Implementation Options\" and the Armv8-M security extension references therein -- the SG / BXNS / BLXNS instruction set used by `libs/ra8_nsc/`'s veneers.")
md.append(" - Ch 16 \"Memory Protection Unit (MPU)\" -- the `.gnu.sgstubs` linker section must land in a region the Secure MPU marks as Secure-execute-only and Non-Secure-callable; wires this up.")
md.append("- **Security feature overview (cross-cutting)**")
md.append(" - Ch 51 \"Security Features\" -- top-level security feature index; pointer to RSIP, secure debug, lifecycle.")
md.append(" - Ch 52 \"Renesas Secure IP (RSIP-E50D)\" -- key vault, AES, SHA, TRNG -- `key_vault.c` lives behind these.")
md.append("")

with open(dst, "w", encoding="utf-8") as out:
    out.write("\n".join(md) + "\n")
PYEOF

echo "Wrote $OUT_FILE"
