def _assert_generated_body(root: Path, generator: str, canonical: str, failures: list[str]) -> None:
    """Assert generated provenance requires real generated content."""
    record, findings = generated_records(
        "generated.py", canonical, frozenset({"generated.py", generator}), root
    )
    expect(
        len(record) == 1 and not findings,
        "must fire: canonical generated marker has provenance and a real body",
        failures,
    )
    for body in (
        "",
        "\n\n",
        "# comment only\n",
        "/* comment only */\n",
        "/* unterminated comment only\n",
    ):
        marker_only = "# @generated by tools/generator.py -- fixture recipe\n" + body
        record, problems = generated_records(
            "generated.py", marker_only, frozenset({"generated.py", generator}), root
        )
        expect(
            not record and any(item.code == "generated-marker-without-body" for item in problems),
            "must fire: marker-only, blank-only, and comment-only artifacts do not waive",
            failures,
        )
    for text in (
        'value = "@generated by tools/generator.py -- string prose"\n',
        "\n" * 40 + canonical,
    ):
        waiver, problems = effective_head_waiver(text, tracked_paths=frozenset({generator}))
        expect(
            waiver is None and not problems,
            "quiet: prose and deep generated hints do not waive",
            failures,
        )


def _assert_generated_syntax(generator: str, failures: list[str]) -> None:
    """Assert malformed and punctuation-only marker syntax fails closed."""
    for malformed in (
        "# @generated\n",
        "# @generated by\n",
        "# FILE-SIZE-OK\n",
        "# FILE-SIZE-OK:\n",
    ):
        waiver, problems = effective_head_waiver(malformed)
        expect(
            waiver is None and any(item.code == "malformed-generated-marker" for item in problems),
            "must fire: bare and malformed generated/file-size markers are inventoried",
            failures,
        )
    for punctuation in ("-", "--", ":", "()"):
        text = f"# @generated by tools/generator.py {punctuation}\nVALUE = 1\n"
        waiver, problems = effective_head_waiver(text, tracked_paths=frozenset({generator}))
        expect(
            waiver is None
            and any(item.code == "non-substantive-waiver-reason" for item in problems),
            "must fire: delimiter-only generated rationales cannot waive",
            failures,
        )
    waiver, problems = effective_head_waiver("# FILE-SIZE-OK: -\nVALUE = 1\n")
    expect(
        waiver is None and any(item.code == "non-substantive-waiver-reason" for item in problems),
        "must fire: delimiter-only FILE-SIZE-OK rationale cannot waive",
        failures,
    )


def _assert_generated_provenance(root: Path, canonical: str, failures: list[str]) -> None:
    """Assert generator identity is tracked, real, and distinct from output."""
    self_marker = "# @generated by tools/generated.py -- deterministic self fixture\nVALUE = 1\n"
    record, problems = generated_records(
        "tools/generated.py", self_marker, frozenset({"tools/generated.py"}), root
    )
    expect(
        not record and any(item.code == "self-generated-provenance" for item in problems),
        "must fire: a generated artifact cannot name itself as its generator",
        failures,
    )
    missing_marker = (
        "# @generated by tools/missing.py -- deterministic missing fixture\nVALUE = 1\n"
    )
    record, problems = generated_records(
        "generated.py",
        missing_marker,
        frozenset({"generated.py", "tools/missing.py"}),
        root,
    )
    expect(
        not record and any(item.code == "missing-generated-provenance" for item in problems),
        "must fire: tracked text cannot impersonate a missing generator file",
        failures,
    )
    _waiver, problems = effective_head_waiver(canonical, tracked_paths=frozenset({"generated.py"}))
    expect(
        any(item.code == "untracked-generated-provenance" for item in problems),
        "must fire: generated provenance must resolve to a tracked path",
        failures,
    )
    _assert_generator_identity(root, failures)


def _assert_generator_identity(root: Path, failures: list[str]) -> None:
    """Assert generator identity rejects symlink, hard-link, and nonregular routes."""
    artifact = root / "generated.py"
    artifact.write_text(
        "# @generated by tools/alias.py -- symlink loop fixture\nVALUE = 1\n",
        encoding="ascii",
    )
    (root / "tools" / "alias.py").symlink_to(artifact)
    tracked = frozenset({"generated.py", "tools/alias.py", "tools/linked.py", "tools/dir.py"})
    record, problems = generated_records("generated.py", artifact.read_text(), tracked, root)
    expect(
        not record and any(item.code == "symlinked-generated-provenance" for item in problems),
        "must fire: a symlink generator cannot launder self-provenance",
        failures,
    )
    escape = root / "tools" / "escape.py"
    escape.symlink_to(root.parent / "outside-generator.py")
    text = "# @generated by tools/escape.py -- escaping symlink fixture\nVALUE = 1\n"
    record, problems = generated_records(
        "generated.py", text, tracked | frozenset({"tools/escape.py"}), root
    )
    expect(
        not record and any(item.code == "symlinked-generated-provenance" for item in problems),
        "must fire: a symlink pointing outside the repository cannot waive",
        failures,
    )
    (root / "tools" / "linked.py").hardlink_to(artifact)
    text = "# @generated by tools/linked.py -- hard-link loop fixture\nVALUE = 1\n"
    artifact.write_text(text, encoding="ascii")
    record, problems = generated_records("generated.py", text, tracked, root)
    expect(
        not record and any(item.code == "self-generated-provenance" for item in problems),
        "must fire: a hard-linked generator shares the artifact's file identity",
        failures,
    )
    (root / "tools" / "dir.py").mkdir()
    text = "# @generated by tools/dir.py -- nonregular generator fixture\nVALUE = 1\n"
    record, problems = generated_records("generated.py", text, tracked, root)
    expect(
        not record and any(item.code == "missing-generated-provenance" for item in problems),
        "must fire: a directory is not a regular generator file",
        failures,
    )
    text = "# @generated by tools/generator.py -- distinct real generator fixture\nVALUE = 1\n"
    artifact.write_text(text, encoding="ascii")
    record, problems = generated_records(
        "generated.py", text, frozenset({"generated.py", "tools/generator.py"}), root
    )
    expect(
        len(record) == 1 and not problems,
        "quiet: a distinct regular tracked generator still waives",
        failures,
    )
    artifact.unlink()


