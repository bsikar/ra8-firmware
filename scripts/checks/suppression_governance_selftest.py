def _assert_census_immutability(failures: list[str]) -> None:
    """Assert every authority mutation route is rejected and clean reads pass."""
    protected = {"EXEMPT_PREFIXES", "PATH_CLASS"}
    modules = {"check_fixture": frozenset({"AUTH"})}
    must_fire = _census_mutation_fixtures()
    for label, source in must_fire.items():
        tree = ast.parse(source)
        found = mutation_findings("fixture.py", tree, protected, modules)
        expect(bool(found), f"must fire: authority {label} is rejected", failures)
    quiet = (
        "import check_fixture as mod\n"
        "EXEMPT_PREFIXES = ('a/', 'b/')\n"
        "OTHER = tuple(sorted(EXEMPT_PREFIXES))\n"
        "def f(rel):\n"
        "    seen = set()\n"
        "    seen.update(EXEMPT_PREFIXES)\n"
        "    seen.update(mod.AUTH)\n"
        "    seen.add(rel)\n"
        "    fields = vars(rel)\n"
        "    return rel.startswith(EXEMPT_PREFIXES) and seen and fields\n"
    )
    found = mutation_findings("fixture.py", ast.parse(quiet), protected, modules)
