def _assert_scope_value_semantics(failures: list[str]) -> None:
    """Assert explicit AST schemas preserve values, reasons, and identity digests."""
    expr = ast.parse("VALUE = ('path with spaces/', 'two/')\n").body[0]
    expect(isinstance(expr, ast.Assign), "fixture AST is one assignment", failures)
    if not isinstance(expr, ast.Assign):
        return
    values = _resolve(expr.value, {}, "scripts/checks/check_suppressions.py")
    expect(
        [item.value for item in values] == ["path with spaces/", "two/"],
        "must fire: paths containing spaces remain concrete values, never reasons",
        failures,
    )
    reasoned = ast.parse("VALUE = (('path with spaces/', 'why'),)\n").body[0]
    expect(isinstance(reasoned, ast.Assign), "reason fixture AST is one assignment", failures)
    if isinstance(reasoned, ast.Assign):
        values = _resolve(reasoned.value, {}, "fixture.py", reasoned_pairs=True)
        expect(
            values == [PolicyValue("path with spaces/", "why")],
            "must fire: explicit pair schema accepts a one-word rationale",
            failures,
        )
    malformed = ast.parse("VALUE = (('path/', ''),)\n").body[0]
    if isinstance(malformed, ast.Assign):
        expect(
            not _resolve(malformed.value, {}, "fixture.py", reasoned_pairs=True),
            "must fire: explicit pair schema rejects an empty or ambiguous rationale",
            failures,
        )
    schema = AuthoritySchema("path-exclusion")
    original = {
        "fixture.py:EXCLUDED": ResolvedAuthority(
            "fixture.py", 1, "EXCLUDED", schema, (PolicyValue("one"), PolicyValue("two"))
        )
    }
    swapped = {
        "fixture.py:EXCLUDED": ResolvedAuthority(
            "fixture.py", 1, "EXCLUDED", schema, (PolicyValue("one"), PolicyValue("three"))
        )
    }
    expect(
        _authority_value_digest(original) != _authority_value_digest(swapped),
        "must fire: same-count authority value swaps change the authenticated digest",
        failures,
    )


