#!/bin/bash
# ra8-firmware - MISRA-C 2023 Static Analysis Script
#
# Runs cppcheck with the MISRA addon configured for the MISRA-C 2023 rule
# set across libs/ and examples/ (excluding libs/third_party/), parses the
# raw cppcheck output, and emits a summary report at:
#
#     build/misra-report.txt
#
# Format (one violation per line, tab-separated):
#     <rule>\t<severity>\t<file>:<line>\t<message>
#
# Usage:
#   ./scripts/checks/misra_check.sh             # Generate report (exit 0)
#   ./scripts/checks/misra_check.sh --check     # Treat regressions as errors
#   ./scripts/checks/misra_check.sh --help
#
# Prerequisites:
#   cppcheck >= 2.10 with the misra.py addon
#
# Copyright (c) 2026 Brighton Sikarskie
# SPDX-License-Identifier: MIT

set -euo pipefail
set +H

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

print_status() { echo -e "${BLUE}[INFO]${NC} $1" >&2; }
print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1" >&2; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1" >&2; }
print_error() { echo -e "${RED}[ERROR]${NC} $1" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FIRMWARE_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

# ---------------------------------------------------------------------------
# Baseline pinned at first run (2026-05-01). Update intentionally.
# ---------------------------------------------------------------------------
BASELINE_TOTAL=${BASELINE_TOTAL:-MISRA_BASELINE_PLACEHOLDER}

CHECK_MODE=false

usage() {
  echo "ra8-firmware - MISRA-C 2023 Lint"
  echo ""
  echo "Usage: $0 [--check] [--help]"
  echo ""
  echo "  --check  Treat any growth above the pinned baseline as an error."
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --check)
      CHECK_MODE=true
      shift
      ;;
    --help | -h)
      usage
      exit 0
      ;;
    *)
      print_error "Unknown option: $1"
      usage
      exit 2
      ;;
  esac
done

if ! command -v cppcheck >/dev/null 2>&1; then
  print_error "cppcheck not found in PATH. Install with: brew install cppcheck"
  exit 2
fi

cd "$FIRMWARE_DIR"

SUPPRESSIONS="$FIRMWARE_DIR/.cppcheck-suppressions"
BUILD_DIR="$FIRMWARE_DIR/build"
mkdir -p "$BUILD_DIR"
RAW="$BUILD_DIR/misra-raw.txt"
REPORT="$BUILD_DIR/misra-report.txt"

# ---------------------------------------------------------------------------
# MISRA addon config - request the 2023 rule set via misra.py.
# ---------------------------------------------------------------------------
MISRA_CFG="$BUILD_DIR/misra-2023.json"
cat >"$MISRA_CFG" <<'JSON'
{
  "script": "misra.py",
  "args": ["--misra-version=2023"]
}
JSON

ADDON_DIR=""
for candidate in /opt/homebrew/share/Cppcheck/addons /usr/share/cppcheck/addons /usr/local/share/Cppcheck/addons; do
  if [[ -d "$candidate" ]]; then
    ADDON_DIR="$candidate"
    break
  fi
done
if [[ -z "$ADDON_DIR" || ! -f "$ADDON_DIR/misra.py" ]]; then
  print_error "MISRA addon (misra.py) not found alongside this cppcheck install"
  exit 2
fi

INCLUDE_DIRS=(
  -Ilibs/ra8_core/inc
  -Ilibs/ra8_hal/inc
  -Ilibs/ra8_nsc/inc
  -Isrc/inc
)

print_status "Running cppcheck MISRA-C 2023 lint ..."
set +e
cppcheck \
  --addon="$MISRA_CFG" \
  --enable=warning,style \
  --inline-suppr \
  --suppressions-list="$SUPPRESSIONS" \
  --suppress=missingIncludeSystem \
  --suppress=unmatchedSuppression \
  --suppress=*:libs/third_party/* \
  -ilibs/third_party \
  --std=c11 \
  --platform=unix32 \
  --language=c \
  --quiet \
  --error-exitcode=0 \
  "${INCLUDE_DIRS[@]}" \
  libs examples \
  2>"$RAW"
set -e

# Parse the raw output. cppcheck MISRA diagnostics look like:
#   path/file.c:123:5: style: misra violation ... [misra-c2012-15.5]
# (cppcheck currently emits the misra-c2012-* identifier even when the
# 2023 rule set is selected; the rule numbering is the same.) We extract:
#     rule \t severity \t file:line \t message
{
  echo "# MISRA-C 2023 report -- ra8-firmware"
  echo "# Generated by scripts/checks/misra_check.sh"
  printf '# Format: <rule>\\t<severity>\\t<file>:<line>\\t<message>\\n'
  echo "#"
  grep -E '\[misra-[A-Za-z0-9.\-]+\]' "$RAW" | awk '
        {
            # Trailing [misra-...] is the rule.
            n = match($0, /\[misra-[A-Za-z0-9.\-]+\]/);
            rule = substr($0, RSTART+1, RLENGTH-2);
            tail = $0;
            sub(/ *\[misra-[A-Za-z0-9.\-]+\] *$/, "", tail);
            # Determine severity word.
            sev = "style";
            if (match(tail, /: (error|warning|style|performance|portability|information): /)) {
                sev = substr(tail, RSTART+2, RLENGTH-4);
            }
            # File:line are first two colon-separated tokens.
            split(tail, parts, ":");
            file = parts[1];
            line = parts[2];
            # Drop "file:line:col: severity:" prefix to get the message body.
            msg = tail;
            sub(/^[^:]+:[0-9]+:[0-9]+: [a-z]+: */, "", msg);
            printf("%s\t%s\t%s:%s\t%s\n", rule, sev, file, line, msg);
        }
    ' | sort -u
} >"$REPORT"

TOTAL=$(grep -cE '^misra-' "$REPORT" || true)

print_status "MISRA report: $REPORT"
print_status "Raw cppcheck output: $RAW"
print_status "Unique MISRA violations: $TOTAL  (baseline: $BASELINE_TOTAL)"

if [[ "$TOTAL" -gt 0 ]]; then
  print_warning "Top 10 most-violated rules:"
  awk -F'\t' '/^misra-/ {print $1}' "$REPORT" | sort | uniq -c | sort -rn | head -10 >&2 || true
fi

if $CHECK_MODE; then
  if [[ "$TOTAL" -gt "$BASELINE_TOTAL" ]]; then
    print_error "MISRA regression: $TOTAL > baseline $BASELINE_TOTAL"
    exit 1
  fi
  print_success "MISRA-C 2023 check passed (<= baseline)"
else
  print_success "MISRA-C 2023 lint completed (advisory mode)"
fi

exit 0
