"""Gate: every Zig build root is either documented or excluded on purpose.

The multi-language documentation architecture (#900) puts Zig autodoc at
``/api/zig/<unit>/``, generated by ``scripts/builders/docs_zig.sh`` from the
units listed in ``config/zig_doc_units.json``. A manifest alone rots: as the
library ports land, a new ``build.zig`` would simply never appear on the site
and nothing would say so.

So this gate derives the truth from the tree (``git ls-files`` for
``build.zig``) and requires every build root to appear exactly once in the
manifest, either under ``documented`` or under ``excluded`` with a written
reason. A documented unit must additionally declare a ``docs`` step in its own
``build.zig``, because that step is what the builder drives; a manifest entry
pointing at a unit with no ``docs`` step would fail only at site-build time.

Run::

    check_zig_doc_units.py --check      # the gate
    check_zig_doc_units.py --selftest   # gate probes, no repository state
    check_zig_doc_units.py --emit-units # TSV consumed by docs_zig.sh
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = REPO_ROOT / "config" / "zig_doc_units.json"
DOCS_STEP_MARKER = 'b.step("docs"'


def declares_docs_step(source: str) -> bool:
    """True when a live (non-commented) line declares the docs step.

    A plain substring search over the whole file also matches a line that has
    been commented out, which is exactly the state a half-reverted unit is left
    in, so the gate would pass while `zig build docs` has no step to run.
    """
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith("//"):
            continue
        if DOCS_STEP_MARKER in stripped:
            return True
    return False


def load_manifest(path: Path) -> dict:
    """Return the parsed manifest, or exit 1 with a precise diagnostic."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        print(f"check_zig_doc_units.py: {path} not found", file=sys.stderr)
        raise SystemExit(1)
    except json.JSONDecodeError as error:
        print(f"check_zig_doc_units.py: {path}: {error}", file=sys.stderr)
        raise SystemExit(1)


def tracked_build_roots(root: Path) -> list[str]:
    """Every directory holding a tracked build.zig, nearest-path order."""
    listing = subprocess.run(
        ["git", "ls-files", "*build.zig"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.split()
    return sorted({str(Path(entry).parent) for entry in listing})


def manifest_problems(manifest: dict, build_roots: list[str], root: Path) -> list[str]:
    """Every way the manifest and the tree can disagree, as plain sentences."""
    problems: list[str] = []
    documented = manifest.get("documented", [])
    excluded = manifest.get("excluded", [])

    seen: dict[str, str] = {}
    for entry in documented:
        build_root = entry.get("build_root", "")
        name = entry.get("name", "")
        if not build_root or not name:
            problems.append(f"documented entry needs both name and build_root: {entry!r}")
            continue
        if build_root in seen:
            problems.append(f"{build_root} is listed twice ({seen[build_root]} and documented)")
        seen[build_root] = "documented"
        build_file = root / build_root / "build.zig"
        if not build_file.is_file():
            problems.append(f"documented unit {name} has no {build_root}/build.zig")
            continue
        if not declares_docs_step(build_file.read_text(encoding="utf-8")):
            problems.append(
                f"documented unit {name} declares no docs step in {build_root}/build.zig "
                f"(expected {DOCS_STEP_MARKER})"
            )

    for entry in excluded:
        build_root = entry.get("build_root", "")
        if not build_root:
            problems.append(f"excluded entry needs a build_root: {entry!r}")
            continue
        if build_root in seen:
            problems.append(f"{build_root} is listed twice ({seen[build_root]} and excluded)")
        seen[build_root] = "excluded"
        if not entry.get("reason", "").strip():
            problems.append(f"excluded unit {build_root} needs a reason")

    for build_root in build_roots:
        if build_root not in seen:
            problems.append(
                f"{build_root}/build.zig is in neither list: add it to config/zig_doc_units.json "
                "as documented (with a docs step) or excluded (with a reason)"
            )

    for build_root in seen:
        if build_root not in build_roots:
            problems.append(f"{build_root} is in the manifest but holds no tracked build.zig")

    return problems


def emit_units(manifest: dict) -> str:
    """TSV the shell builder reads: name, build_root, title, summary."""
    rows = []
    for entry in manifest.get("documented", []):
        rows.append(
            "\t".join(
                [
                    entry.get("name", ""),
                    entry.get("build_root", ""),
                    entry.get("title", entry.get("name", "")),
                    entry.get("summary", ""),
                ]
            )
        )
    return "\n".join(rows)


def selftest() -> int:
    """Probe the gate's own verdicts, so a broken gate cannot pass silently."""
    failures = []

    good = {
        "documented": [{"name": "unit", "build_root": "u"}],
        "excluded": [{"build_root": "x", "reason": "fixture"}],
    }
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        tree = Path(tmp)
        (tree / "u").mkdir()
        (tree / "u" / "build.zig").write_text('b.step("docs", "x");\n', encoding="utf-8")
        (tree / "x").mkdir()
        (tree / "x" / "build.zig").write_text("// fixture\n", encoding="utf-8")

        if manifest_problems(good, ["u", "x"], tree):
            failures.append("a complete manifest should pass")

        if not manifest_problems(good, ["u", "x", "newlib"], tree):
            failures.append("an unlisted build root should fail")

        no_step = {"documented": [{"name": "unit", "build_root": "x"}], "excluded": []}
        if not manifest_problems(no_step, ["x"], tree):
            failures.append("a documented unit with no docs step should fail")

        no_reason = {"documented": [], "excluded": [{"build_root": "x", "reason": "  "}]}
        if not manifest_problems(no_reason, ["x"], tree):
            failures.append("an excluded unit with no reason should fail")

        (tree / "c").mkdir()
        (tree / "c" / "build.zig").write_text('// b.step("docs", "x");\n', encoding="utf-8")
        commented = {"documented": [{"name": "unit", "build_root": "c"}], "excluded": []}
        if not manifest_problems(commented, ["c"], tree):
            failures.append("a commented-out docs step should fail")

        stale = {"documented": [], "excluded": [{"build_root": "gone", "reason": "r"}]}
        if not manifest_problems(stale, [], tree):
            failures.append("a manifest entry with no build.zig should fail")

    for failure in failures:
        print(f"check_zig_doc_units.py: selftest: {failure}", file=sys.stderr)
    if failures:
        return 1
    print("check_zig_doc_units.py: selftest OK")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="run the gate")
    parser.add_argument("--selftest", action="store_true", help="probe the gate itself")
    parser.add_argument("--emit-units", action="store_true", help="TSV for docs_zig.sh")
    args = parser.parse_args(argv)

    if args.selftest:
        return selftest()

    manifest = load_manifest(MANIFEST_PATH)

    if args.emit_units:
        print(emit_units(manifest))
        return 0

    problems = manifest_problems(manifest, tracked_build_roots(REPO_ROOT), REPO_ROOT)
    for problem in problems:
        print(f"check_zig_doc_units.py: {problem}", file=sys.stderr)
    if problems:
        return 1
    documented = len(manifest.get("documented", []))
    excluded = len(manifest.get("excluded", []))
    print(f"check_zig_doc_units.py: OK ({documented} documented, {excluded} excluded)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
