# scripts/builders/docs_zig.sh -- generate the Zig autodoc half of the
# documentation site (#900).
#
# Doxygen owns the C ABI headers, MkDocs owns the Markdown hub, and Zig
# autodoc owns the native Zig modules: Doxygen cannot parse a `.zig` file at
# all, so anything that moves from C to Zig behind an unchanged C header would
# otherwise lose its implementation-side reference. ADR-0005 puts that output
# at `/api/zig/<unit>/`; this script is what fills it.
#
# Every documented unit declares its OWN `docs` step in its `build.zig`, built
# from the same module the unit actually compiles (include paths, C sources,
# imports and all). That is deliberate: reconstructing those flags in a shell
# script would silently rot the first time a module gained an include path.
# This script only drives those steps and assembles the landing index.
#
# The set of units is config/zig_doc_units.json, and
# scripts/checks/check_zig_doc_units.py fails closed when a Zig build root in
# the tree is in neither list, so a newly ported library cannot quietly land
# without documentation.
#
# Usage:
#   bash scripts/builders/docs_zig.sh              -- build into build/docs/api/zig/
#   bash scripts/builders/docs_zig.sh --gate       -- build into build/docs-gate/api/zig/
#   bash scripts/builders/docs_zig.sh --out DIR    -- build into DIR
#
# Output is generated, never committed: build/ is ignored in its entirety.
#
# zig is resolved from ZIG, else PATH. CI resolves the pinned toolchain through
# scripts/ci/lib/lang_toolchains.sh before any gate runs, so a gate that reaches
# this script already has the pin on PATH.
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"
MANIFEST="${ROOT_DIR}/config/zig_doc_units.json"

OUTPUT_DIR=""
GATE_MODE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --gate)
      GATE_MODE=1
      shift
      ;;
    --out)
      [[ $# -ge 2 ]] || {
        echo "docs_zig.sh: --out needs a directory" >&2
        exit 2
      }
      OUTPUT_DIR="$2"
      shift 2
      ;;
    -h | --help)
      sed -n '3,30p' "${BASH_SOURCE[0]}"
      exit 0
      ;;
    *)
      echo "docs_zig.sh: unknown argument '$1'" >&2
      exit 2
      ;;
  esac
done

if [[ -z "${OUTPUT_DIR}" ]]; then
  if [[ "${GATE_MODE}" -eq 1 ]]; then
    OUTPUT_DIR="${ROOT_DIR}/build/docs-gate/api/zig"
  else
    OUTPUT_DIR="${ROOT_DIR}/build/docs/api/zig"
  fi
fi

if [[ ! -r "${MANIFEST}" ]]; then
  echo "docs_zig.sh: ${MANIFEST} not found" >&2
  exit 1
fi

ZIG_BIN="${ZIG:-zig}"
if ! command -v "${ZIG_BIN}" > /dev/null 2>&1; then
  echo "docs_zig.sh: zig not found on PATH (set ZIG=/path/to/zig)." >&2
  echo "docs_zig.sh: CI resolves the pin via scripts/ci/lib/lang_toolchains.sh." >&2
  exit 1
fi
echo "docs_zig.sh: using zig $("${ZIG_BIN}" version) ($(command -v "${ZIG_BIN}"))"

mkdir -p "${OUTPUT_DIR}"

# name<TAB>build_root<TAB>title<TAB>summary, manifest order preserved.
UNITS="$(python3 "${ROOT_DIR}/scripts/checks/check_zig_doc_units.py" --emit-units)"

if [[ -z "${UNITS}" ]]; then
  echo "docs_zig.sh: no documented Zig units in ${MANIFEST}" >&2
  exit 1
fi

while IFS=$'\t' read -r name build_root title summary; do
  [[ -n "${name}" ]] || continue
  unit_dir="${ROOT_DIR}/${build_root}"
  echo "docs_zig.sh: ${name} (${build_root})"
  rm -rf "${OUTPUT_DIR:?}/${name}"
  (
    cd "${unit_dir}"
    "${ZIG_BIN}" build docs --prefix "${OUTPUT_DIR}"
  )
  if [[ ! -f "${OUTPUT_DIR}/${name}/index.html" ]]; then
    echo "docs_zig.sh: ${name} produced no index.html under ${OUTPUT_DIR}/${name}" >&2
    exit 1
  fi
done <<< "${UNITS}"

INDEX="${OUTPUT_DIR}/index.html"
{
  cat << 'HTML_HEAD'
<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>ra8-firmware Zig API reference</title>
  </head>
  <body>
    <h1>ra8-firmware Zig API reference</h1>
    <p>
      Generated by <code>zig build docs</code> per unit. The C ABI reference
      lives under <code>/api/c/</code> and the Markdown hub at <code>/</code>.
    </p>
    <ul>
HTML_HEAD
  while IFS=$'\t' read -r name build_root title summary; do
    [[ -n "${name}" ]] || continue
    printf '      <li><a href="./%s/index.html">%s</a> &mdash; %s <code>%s</code></li>\n' \
      "${name}" "${title}" "${summary}" "${build_root}"
  done <<< "${UNITS}"
  cat << 'HTML_TAIL'
    </ul>
  </body>
</html>
HTML_TAIL
} > "${INDEX}"

echo "docs_zig.sh: wrote ${INDEX}"
