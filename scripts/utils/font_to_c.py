#!/usr/bin/env python3
#
# scripts/utils/font_to_c.py -- emit a C source file embedding a binary font
# blob as a `const unsigned char[]` array plus its length, for baking a font
# into internal flash (.rodata).
#
# Dependency-free (stdlib only) so it runs at build time on any host without a
# venv. The generated .c is written to the build directory and is NOT committed,
# which keeps the large hex array out of the QC gates (magic-numbers / format).
#
# Usage:
#   font_to_c.py <input-font> <output.c> <symbol_name>
#
# The output defines, against the declarations in baked_font.h:
#   const unsigned char <symbol_name>[]  = { ... };
#   const unsigned int  <symbol_name>_len = <N>;
#
# The Latin-1 subset checked in at libs/fonts/arnopro_latin1.otf was produced
# with fonttools (in a throwaway venv) from libs/fonts/ArnoPro-Regular.otf:
#   pyftsubset ArnoPro-Regular.otf \
#     --unicodes='0020-00FF,2013,2014,2018,2019,201C,201D,2026' \
#     --output-file=arnopro_latin1.otf \
#     --no-hinting --desubroutinize --glyph-names --notdef-outline
#
# Copyright (c) 2026 Brighton Sikarskie
# SPDX-License-Identifier: MIT
#
import sys
import pathlib


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write("usage: font_to_c.py <input-font> <output.c> <symbol_name>\n")
        return 2
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    data = pathlib.Path(src).read_bytes()
    if not data:
        sys.stderr.write(f"font_to_c.py: empty input {src}\n")
        return 1

    out = []
    out.append("/* GENERATED by scripts/utils/font_to_c.py -- do not edit. */")
    out.append(f'/* Source: {pathlib.Path(src).name} ({len(data)} bytes). */')
    out.append('#include "baked_font.h"')
    out.append("")
    out.append(f"const unsigned char {name}[] = {{")
    # 16 bytes per line keeps the file readable; it is build-only, not committed.
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.append("  " + "".join(f"0x{b:02X}, " for b in chunk).rstrip())
    out.append("};")
    out.append(f"const unsigned int {name}_len = {len(data)}U;")
    out.append("")

    pathlib.Path(dst).write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
