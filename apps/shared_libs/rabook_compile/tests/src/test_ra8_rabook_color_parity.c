/**
 * @file test_ra8_rabook_color_parity.c
 * @brief Host-vs-device byte-identity gate for the default colour raster path (#337).
 *
 * @details
 * Compiling the same source image on the host and on the device used to produce
 * DIFFERENT bytes: two RGB->gray8 luma transforms (PIL ITU-R 601-2 vs stb_image's
 * integer `stbi__compute_y`) and two gray8->nibble quantisers (PIL palette-snap on
 * the host default path vs the device kernel `(v + 8) / 17`). Since the default is
 * the no-downscale path (issue #210), the divergent path was the one that ran, so
 * a colour raster was not round-trip-verifiable byte-identical -- breaking the
 * golden-render regression model (issue #337).
 *
 * The fix routes BOTH host and device through one luma and one quantiser: the host
 * `tools/epub_compile` decodes with the SAME integer luma stb_image applies
 * (`gray4_kernel.stb_compute_y`) and packs with the SAME kernel
 * (`gray4_kernel.gray4_encode`, mirroring `ra8_rabook_gray4_encode`). This test is
 * the proof: it decodes the baked colour PNG with the firmware's stb_image
 * (req_comp = 1 -- the exact on-device decode + luma) and encodes it with the
 * firmware gray4 kernel, then asserts the packed bytes are byte-identical to the
 * host golden `s_color_golden` that `tools/epub_compile` emits for the SAME PNG on
 * its default no-downscale path. A match means the decode, the luma, and the
 * quantiser are one algorithm host-vs-device -- the whole point of #337.
 *
 * The fixture rabook_color_parity_fixture.h is regenerated by
 * `just tools::rabook_golden` (scripts/gen/rabook_parity_gen.py --color), which
 * bakes the golden straight from the production `BlobBuilder.add_raster_image`, so
 * the golden can never drift from the shipping desktop tool.
 *
 * @par MC/DC:
 * This file adds the end-to-end colour host-vs-device parity vector; it introduces
 * no compound boolean decision of its own (every assertion is a byte-identity
 * equality). The MC/DC vectors for the exercised firmware functions
 * (ra8_rabook_gray4_encode) live in test_ra8_rabook_gray4.c and are unchanged.
 *
 * @since Version 0.1.0
 * @copyright Copyright (c) 2026 Brighton Sikarskie
 * SPDX-License-Identifier: MIT
 *
 * [Ring 4 / EPUB_Compiler] {World: NS}
 */

