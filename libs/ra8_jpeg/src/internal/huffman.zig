//! Huffman tables for the baseline encoder: the four T.81 Annex K.3.3
//! reference specifications and the Annex C canonical code build that turns a
//! BITS/VALUES pair into the code and length look-ups the entropy coder
//! indexes by symbol.

const spec = @import("spec");

/// Codes and lengths indexed by symbol byte. A symbol absent from the
/// specification keeps length zero, which the sink treats as no push.
pub const Table = struct {
    codes: [spec.Huff.max_symbols]u16 = @splat(0),
    sizes: [spec.Huff.max_symbols]u8 = @splat(0),
};

/// One T.81 Annex K.3.3 table: how many codes of each length 1..16, and the
/// symbols in canonical order.
pub const Specification = struct {
    bits: *const [spec.Huff.lengths]u8,
    values: []const u8,

    /// Number of symbols, which is also the DHT segment's value-count.
    pub fn total(self: Specification) u16 {
        var sum: u16 = 0;
        for (self.bits) |count| sum += count;
        return sum;
    }
};

