/// Canonical-build one table, T.81 Annex C "Huffman table specification".
///
/// Walks the BITS list into a run of code lengths, assigns increasing codes
/// within each length and doubles at every length step, then scatters the
/// result to the symbol-indexed look-ups. Returns the symbol count.
pub fn build(table: *Table, specification: Specification) u16 {
    var lengths: [spec.Huff.max_symbols + 1]u8 = @splat(0);
    var count: usize = 0;
    for (specification.bits, 0..) |n, i| {
        for (0..n) |_| {
            lengths[count] = @intCast(i + 1);
            count += 1;
        }
    }
    lengths[count] = 0;

    var codes: [spec.Huff.max_symbols + 1]u16 = @splat(0);
    var code: u16 = 0;
    var width: u8 = if (count > 0) lengths[0] else 0;
    var at: usize = 0;
    while (lengths[at] != 0) {
        while (lengths[at] == width) {
            codes[at] = code;
            code += 1;
            at += 1;
        }
        if (lengths[at] == 0) break;
        while (lengths[at] != width) {
            code <<= 1;
            width += 1;
        }
    }

    for (specification.values, 0..) |symbol, i| {
        table.codes[symbol] = codes[i];
        table.sizes[symbol] = lengths[i];
    }
    return specification.total();
}

/// The four tables a 4:2:0 baseline scan needs, with their DHT value-counts.
pub const Set = struct {
    dc_luma: Table = .{},
    ac_luma: Table = .{},
    dc_chroma: Table = .{},
    ac_chroma: Table = .{},

    total_dc_luma: u16 = 0,
    total_ac_luma: u16 = 0,
    total_dc_chroma: u16 = 0,
    total_ac_chroma: u16 = 0,

    pub fn buildAll(self: *Set) void {
        self.total_dc_luma = build(&self.dc_luma, dc_luma);
        self.total_ac_luma = build(&self.ac_luma, ac_luma);
        self.total_dc_chroma = build(&self.dc_chroma, dc_chroma);
        self.total_ac_chroma = build(&self.ac_chroma, ac_chroma);
    }
};
