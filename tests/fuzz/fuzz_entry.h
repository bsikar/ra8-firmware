/**
 * @file tests/fuzz/fuzz_entry.h
 * @brief The libFuzzer target entry point every fuzz harness defines
 *
 * @par Tag
 * [Ring 6 / TEST] {World: NS}
 *
 * @details
 * libFuzzer drives a target by calling ``LLVMFuzzerTestOneInput`` once per
 * generated input. The driver is linked in from the sanitizer runtime and
 * resolves the symbol by name, so every harness under ``tests/fuzz`` has
 * to define it with external linkage and no first-party caller.
 *
 * The prototype lives here rather than being restated in each harness so
 * the twenty-odd definitions are checked against one contract. Getting the
 * signature wrong is not a compile error in a lone ``.c`` -- it is a
 * mismatched call from the driver at run time.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

/**
 * @brief Run the fuzz target over one libFuzzer-generated input.
 *
 * @details
 * Called repeatedly by the libFuzzer driver, each time with a fresh
 * buffer. The target must tolerate arbitrary bytes, must not exit the
 * process on invalid input, and must leave no state behind that would
 * make the next call behave differently -- libFuzzer treats a
 * non-reproducible crash as a corpus bug.
 *
 * @param[in] data Fuzzer-generated bytes. Never NULL; may be zero-length.
 * @param[in] size Number of bytes readable at @p data.
 *
 * @return Status for the driver.
 * @retval 0 Input consumed. Fuzz targets always return 0; a non-zero
 *           return is reserved by libFuzzer for inputs to reject.
 *
 * @pre @p data is readable for @p size bytes.
 * @pre The harness has completed any one-time setup it needs.
 * @post No allocation or global state survives the call.
 * @post The process is still running unless the target found a real bug.
 *
 * @note Not thread-safe; libFuzzer calls it on one thread.
 *
 * @par Example:
 * @code
 * int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size)
 * {
 *   ra8_thing_parse(data, size);
 *   return 0;
 * }
 * @endcode
 *
 * @since 0.1.0
 */
int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size);
