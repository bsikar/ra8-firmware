/**
 * @file test_ra8_rabook_downscale_parity.c
 * @brief Host-vs-device byte-identity gate for the opt-in image downscale (#213).
 *
 * @details
 * The .rabook image pipeline may downscale a raster when the caller opts in with
 * a max-edge clamp (default off, issue #210). The desktop compiler
 * (tools/epub_compile/epub_compile.py, resampling via tools/epub_compile/
 * gray4_kernel.py) and the firmware (ra8_rabook_gray4_downscale + _encode) MUST
 * emit the same 4-bpp bytes for that path -- one deterministic integer kernel, not
 * a LANCZOS-vs-bilinear exception. Before #213 the desktop tool used PIL LANCZOS,
 * so a downscaled image could not be round-trip-verified byte-identical.
 *
 * This test runs the firmware kernel over a baked 8-bpp source and asserts the
 * packed output is byte-identical to the desktop golden produced by the same
 * integer kernel. Both sides are fed an IDENTICAL source buffer, so the internal_check
 * isolates the resample+quantise kernel (no stb_image-vs-PIL decode confound).
 * The fixture rabook_downscale_parity_fixture.h is regenerated by
 * `make rabook-golden-update` (scripts/gen/rabook_parity_gen.py --downscale),
 * whose generator cross-checks the golden against the production epub_compile.py.
 *
 * @par MC/DC:
 * This file adds the end-to-end host-vs-device parity vector; it introduces no
 * compound boolean decision of its own (every assertion is a byte-identity
 * equality). The MC/DC vectors for the compound decisions inside the exercised
 * functions -- ra8_rabook_gray4_output_dims, _downscale, and _encode -- live in
 * test_ra8_rabook_gray4.c and are unchanged by this gate.
 *
 * @since Version 0.1.0
 * @copyright Copyright (c) 2026 Brighton Sikarskie
 * SPDX-License-Identifier: MIT
 *
 * [Ring 4 / EPUB_Compiler] {World: NS}
 */

