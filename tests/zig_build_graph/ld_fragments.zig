//!
//! The two linker-script fragments `ra8_add_app()` generates per app, ported
//! from cmake/ra8_app/sources.cmake.
//!
//! Both board memory maps `INCLUDE` them by bare name
//! (libs/ra8_board_ek_ra8d2/ld/linker_script.ld:45 and :155, and :53 and :163
//! in the ra8p1 map), so a link that cannot find them fails before it places
//! a single section. CMake writes both unconditionally into the app's binary
//! directory, which is also where the link runs, so the bare name resolves.
//! This build has no such directory, so the files are written into a
//! generated one and that directory goes on the link line as `-L`.
//!
//! An app that names neither keyword still gets both files, as a comment and
//! nothing else. That is not a formality: an absent INCLUDE target is a hard
//! link error, so "nothing to inject" has to be spelled as an empty file
//! rather than as a missing one.

const std = @import("std");

const app_table = @import("app_table.zig");
const cmake_vars = @import("cmake_vars.zig");

const CrossApp = app_table.CrossApp;

pub const pre_memory_name = "ra8_app_pre_memory.ld";
pub const pre_text_name = "ra8_app_pre_text.ld";
pub const composed_name = "ra8_app_composed.ld";

/// `MRAM_LENGTH <size>`. A MEMORY block in an INCLUDEd script cannot be
/// amended by the script that includes it, so the board map reads its bank
/// length through DEFINED(__ra8_app_mram_length) and this fragment supplies
/// the override ahead of the MEMORY block. Empty leaves the canonical map
/// untouched.
pub fn preMemory(b: *std.Build, app: CrossApp) []const u8 {
    const mram_length = app.mram_length orelse
        return "/* Generated by ra8_add_app(). Board memory map used as written. */\n";
    return b.fmt(
        "/* Generated by ra8_add_app(MRAM_LENGTH {s}). Do not edit. */\n" ++
            "__ra8_app_mram_length = {s};\n",
        .{ mram_length, mram_length },
    );
}

/// `SRAM_TEXT <sources>`. Both `.obj` and `.o` spellings are emitted because
/// the object suffix follows the generator and naming only one would silently
/// place nothing under the other. The bare wildcards come first so the
/// `__attribute__((section(".sram_text")))` route that ra8_flash.h documents
/// lands in the same section instead of being placed as an orphan.
pub fn preText(b: *std.Build, app: CrossApp) []const u8 {
    if (app.sram_text.len == 0) {
        return "/* Generated by ra8_add_app(). Nothing to inject ahead of .text. */\n";
    }

    var body = std.ArrayList(u8).init(b.allocator);
    for (app.sram_text) |source| {
        body.writer().print(
            "        *{s}.obj(.text .text.*)\n" ++
                "        *{s}.o(.text .text.*)\n",
            .{ source, source },
        ) catch @panic("OOM");
    }

    const why = std.mem.join(b.allocator, " ", app.sram_text) catch @panic("OOM");
    return b.fmt(
        "/* Generated by ra8_add_app(SRAM_TEXT {s}). Do not edit. */\n" ++
            "    .sram_text : ALIGN(4)\n" ++
            "    {{\n" ++
            "        g_ra8_ls_ssram_text = .;\n" ++
            "        *(.sram_text)\n" ++
            "        *(.sram_text.*)\n" ++
            "{s}" ++
            "        g_ra8_ls_esram_text = .;\n" ++
            "    }} > SRAM AT > MRAM\n" ++
            "    g_ra8_ls_sram_text_load = LOADADDR(.sram_text);\n",
        .{ why, body.items },
    );
}

/// Does this app link a COMPOSED script rather than the board map directly?
///
/// `THREADX_HEAP` and `CPU1_IMAGE` do not inject through the two INCLUDE
/// points above: sources.cmake:1235 writes a third script that INCLUDEs the
/// board map and appends to it, and points -T at that instead. The two
/// fragments above are pulled IN BY the board map; this one WRAPS it.
pub fn composes(app: CrossApp) bool {
    return app.threadx_heap != null or app.cpu1_image;
}

/// `THREADX_HEAP <region>`. One PROVIDE: the origin of the region
/// tx_application_define() carves its pools from. Before #761 the only way to
/// add it was a private copy of the whole 340-line board map, which is why 42
/// apps missed every later platform change.
fn threadxHeap(b: *std.Build, region: []const u8) []const u8 {
    return b.fmt(
        "PROVIDE(g_ra8_threadx_unused_memory_start = ORIGIN({s}));\n",
        .{region},
    );
}

/// `CPU1_IMAGE`. The tracked template, with the board's two addresses
/// substituted exactly as `string(CONFIGURE ... @ONLY)` does at
/// sources.cmake:1139-1141.
///
/// Template and addresses are both READ, never transcribed: cpu1_image.ld.in
/// is where the linker-script checkers see g_ra8_ls_cpu1_mram_start and
/// g_ra8_ls_cpu1_stack_top declared, and cpu1_memory_map.cmake is the one
/// definition of the window since #742. Copying either into Zig would create
/// the second copy that #742 existed to delete.
fn cpu1Image(b: *std.Build, board: []const u8) []const u8 {
    const template_path = b.fmt("{s}/ld/cpu1_image.ld.in", .{board});
    const map_path = b.fmt("{s}/ld/cpu1_memory_map.cmake", .{board});

    const template = read(b, template_path);
    const vars = cmake_vars.parse(b.allocator, read(b, map_path));

    const origin = vars.get("RA8_CPU1_IMAGE_ORIGIN", map_path);
    const stack_top = vars.get("RA8_CPU1_STACK_TOP_EXPR", map_path);

    const with_origin = std.mem.replaceOwned(
        u8,
        b.allocator,
        template,
        "@RA8_CPU1_IMAGE_ORIGIN@",
        origin,
    ) catch @panic("OOM");
    return std.mem.replaceOwned(
        u8,
        b.allocator,
        with_origin,
        "@RA8_CPU1_STACK_TOP_EXPR@",
        stack_top,
    ) catch @panic("OOM");
}

fn read(b: *std.Build, path: []const u8) []const u8 {
    return b.build_root.handle.readFileAlloc(b.allocator, path, 1 << 20) catch |err|
        std.debug.panic("ld_fragments: cannot read {s}: {s}", .{ path, @errorName(err) });
}

/// The composed script: INCLUDE the board map, then append what the keywords
/// asked for, in the order sources.cmake appends them.
///
/// The INCLUDE is spelled ABSOLUTE, as CMake spells it, because the script
/// lives in a generated directory and ld resolves a relative INCLUDE against
/// its own search path. The bare-name INCLUDEs inside the board map still
/// resolve: the -L already points at this same directory.
pub fn composed(b: *std.Build, app: CrossApp) []const u8 {
    var body = std.ArrayList(u8).init(b.allocator);
    const writer = body.writer();

    writer.print(
        "/* Generated by ra8_add_app(). Do not edit. */\nINCLUDE {s}\n",
        .{b.pathFromRoot(app.linker_script)},
    ) catch @panic("OOM");

    if (app.threadx_heap) |region| {
        writer.writeAll(threadxHeap(b, region)) catch @panic("OOM");
    }
    if (app.cpu1_image) {
        writer.writeAll(cpu1Image(b, app.board)) catch @panic("OOM");
    }
    // NS_INLINE_IMAGE is the third composition sources.cmake:1143 appends and
    // is not written here yet; cpu1_pingpong_ipc, the only app in this table
    // that names it, does not link today for an unrelated reason (undefined
    // ra8_sau_configure).

    return body.items;
}

/// Both fragments in one generated directory, ready to hand to the link as a
/// `-L` search path. An app that composes also gets its composed script here,
/// so the one directory carries everything the link reads.
pub fn directory(b: *std.Build, app: CrossApp) std.Build.LazyPath {
    const files = b.addWriteFiles();
    _ = files.add(pre_memory_name, preMemory(b, app));
    _ = files.add(pre_text_name, preText(b, app));
    if (composes(app)) _ = files.add(composed_name, composed(b, app));
    return files.getDirectory();
}
