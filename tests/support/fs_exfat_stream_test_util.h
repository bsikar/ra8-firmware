/**
 * @file fs_exfat_stream_test_util.h
 * @brief Shared fixture for the exFAT streaming-write test executables (#602).
 *
 * @details
 * Builds on `fs_fat_exfat_mutate_test_util.h` -- the 64 MiB RAM-backed exFAT
 * volume, the partition-relative disk pokes and the allocation-bitmap census --
 * and adds what a STREAMING test needs on top:
 *
 *   - a deterministic payload generator and a streamed read-back comparator
 *     that never holds the whole file in RAM, because a test that buffers what
 *     the driver is supposed to stream is testing the wrong thing;
 *   - direct readers for the Stream-extension fields the streaming path owns
 *     (`GeneralSecondaryFlags`, `FirstCluster`, `ValidDataLength`,
 *     `DataLength`) read straight out of the image rather than from the API,
 *     so a handle that lies about itself cannot make an assertion pass;
 *   - `internal_stream_dump_image()`, which writes the filesystem PARTITION to a file when
 *     `RA8_EXFAT_DUMP_DIR` names a directory. That is how the `fsck.exfat -n`
 *     evidence for every scenario in this suite is produced, and it makes that
 *     evidence REPRODUCIBLE rather than a claim:
 *
 *         RA8_EXFAT_DUMP_DIR=/tmp/xf ./test_ra8_fs_exfat_stream
 *         for f in /tmp/xf/[*].img; do fsck.exfat -n "$f"; done
 *
 *     With the variable unset -- which is how CI runs -- it does nothing at
 *     all, so the suite carries no dependency on exfatprogs.
 *
 * Everything here has internal linkage, so each including executable owns a
 * private copy of the fixture state.
 *
 * @copyright Copyright (c) 2026 Brighton Sikarskie
 * SPDX-License-Identifier: MIT
 * @since 0.1.0
 */
#pragma once

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ra8_err.h"
